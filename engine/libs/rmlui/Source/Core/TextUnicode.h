#pragma once

#include "../../Include/RmlUi/Core/StyleTypes.h"
#include "../../Include/RmlUi/Core/Types.h"

namespace Rml {

/**
    Unicode helpers of the text layout (phase 3, p3-text): case mapping for 'text-transform' and the line-break
    opportunities between two characters (a subset of UAX #14 as CSS Text 3 §5 applies it). The tables are generated by
    Utilities/gen_case_tables.py (UnicodeCaseTables.inl, UnicodeLineBreakTables.inl).
 */
namespace TextUnicode {

	// Appends the code point's full uppercase or lowercase mapping (SpecialCasing.txt's unconditional mappings, else
	// UnicodeData.txt's simple one: 'ß' -> "SS", 'İ' -> "i̇"), UTF-8 encoded.
	void AppendUppercase(String& out, Character c);
	void AppendLowercase(String& out, Character c);
	// Appends the simple titlecase mapping ('ǆ' -> 'ǅ'; 'ß' stays 'ß', as in Chromium's 'capitalize').
	void AppendTitlecase(String& out, Character c);

	// The simple mappings alone (one code point).
	Character ToUpper(Character c);
	Character ToLower(Character c);

	// A letter, mark or number (general categories L, M, N): the characters 'capitalize' reads as words.
	bool IsWordCharacter(Character c);
	// Whether 'c' starts a word for 'capitalize' (CSS Text 3 §2.1.1; UAX #29 as Chromium applies it), given the two
	// characters before it ('Null' at the start of the text): a word character after a character that is not one,
	// except across a connector ("x_y"), an apostrophe or middle dot between letters ("don't"), and a separator inside
	// a number ("1,5"). Periods, colons, hyphens and slashes start new words ("E.G.", "Foo-Bar", "A/B").
	bool IsWordStart(Character before_previous, Character previous, Character c);

	// A line-break opportunity between 'before' and 'after', two characters that are not white space, with the given
	// 'word-break' (UAX #14 pair rules for the classes the fork tells apart: after a zero-width space, a soft hyphen, a
	// hyphen or a dash; around ideographs and emoji unless 'keep-all'; never before closing punctuation, after an
	// opening one, around joiners and glue, or before combining marks).
	bool IsLineBreakOpportunity(Character before, Character after, Style::WordBreak word_break);

	// 'c' continues the character before it (a combining mark, a joiner, an emoji modifier, a variation selector): no
	// strong direction of its own (FirstStrongDirection).
	bool ContinuesCluster(Character c);
	// The direction of a run for a font engine that does not resolve bidi (FontEngineInterface::GetBidiRuns' default, fork
	// P6-L1), from its first strongly directional character (Hebrew, Arabic and the other right-to-left scripts; letters
	// of the others): 1 left-to-right, -1 right-to-left, 0 none (digits, punctuation, spaces).
	int FirstStrongDirection(StringView text);

	// U+00AD SOFT HYPHEN: a break opportunity that shows a hyphen when the line breaks there.
	constexpr Character SoftHyphen = static_cast<Character>(0x00AD);

	// Decodes the UTF-8 code point at 'p' (before 'end'); 'Null' at the end, U+FFFD for an invalid byte. Advances 'p'.
	Character DecodeUTF8(const char*& p, const char* end);

} // namespace TextUnicode
} // namespace Rml
