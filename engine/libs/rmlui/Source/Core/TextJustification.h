namespace Rml {

/**
    Justification of a line (p6-justify: 'text-align: justify' and 'text-justify', CSS Text 3 §7.3), as Chromium 153 does it
    (third_party/blink/renderer/core/layout/inline/justification_utils.cc, platform/text/justification_opportunity.cc,
    platform/fonts/shaping/shape_result_spacing.cc): the free space of the line is shared equally by its justification
    opportunities, the last one taking what rounding leaves. The tables are generated by Utilities/gen_case_tables.py
    (UnicodeJustificationTables.inl).
 */
namespace TextJustification {

	// Spaces, tabs, line feeds and no-break spaces: an opportunity after each one (Chromium's Character::TreatAsSpace).
	inline bool TreatAsSpace(Character c)
	{
		const char32_t v = (char32_t)c;
		return v == 0x20 || v == 0x09 || v == 0x0A || v == 0xA0;
	}
	// Ideographs, kana, CJK symbols and emoji: opportunities before and after each one with 'text-justify: auto'.
	bool IsCjkIdeographOrSymbol(Character c);
	// A letter of a script whose letters join (Arabic, Syriac, Mongolian, ...): no opportunity inside a run of them.
	bool IsCursiveScript(Character c);
	// Default_Ignorable_Code_Point: never an opportunity (below U+0100 only the soft hyphen).
	bool IsDefaultIgnorable(Character c);

	// The character an atomic inline (an inline-block, an image) is justified as.
	constexpr Character ObjectReplacementCharacter = static_cast<Character>(0xFFFC);

	// The extended grapheme clusters of a UTF-8 string (UAX #29, every rule: CR LF, controls, Hangul syllables, combining
	// marks, joiners, spacing marks, prepended concatenation marks, Indic conjuncts, emoji sequences, regional indicator
	// pairs): the byte offset and code point of the first character of each one, in order.
	struct Cluster {
		int offset;
		Character first;
	};
	void GetClusters(StringView text, Vector<Cluster>& out);

} // namespace TextJustification

/**
    Chromium's JustificationContext: the opportunities before and after each character of a line, visited in order (the
    logical order, reversed for a right-to-left line), from the state the previous characters left.
 */
class JustificationContext {
public:
	struct Opportunities {
		bool before = false;
		bool after = false;
	};

	// The opportunities around 'c' justified with 'method'.
	Opportunities Check(Style::TextJustify method, Character c);

	bool IsAfterOpportunity() const { return after_opportunity; }

private:
	enum class Type : uint8_t { Normal, AtomicInline, Cursive };
	Type previous_type = Type::Normal;
	// No opportunity at the start of a line.
	bool after_opportunity = true;
};

/**
    One piece of a line to justify: a text (its UTF-8 characters up to where the line is justified) or an atomic inline,
    with the 'text-justify' of its element.
 */
struct JustificationRun {
	StringView text;
	Style::TextJustify method = Style::TextJustify::Auto;
	bool atomic = false;

	// The result: the spacing of the text's characters (byte offsets into 'text', sorted), and the space added before
	// and after an atomic inline, or before and after all of the text's characters together.
	Vector<JustificationSpacing> spacing;
	float before = 0.f;
	float after = 0.f;

	float GetTotal() const { return before + after; }
};

/**
    Distributes 'space' (> 0) over the justification opportunities of the runs, visited in order, or from the last
    character of the last run for a right-to-left line ('reverse'). The opportunity after the last character visited is
    not used. Returns false, and changes nothing, when there is no opportunity (the line is then aligned to its start).
*/
bool JustifyRuns(Vector<JustificationRun>& runs, float space, bool reverse);

/// The space before the character at byte offset 'end' of the string: the sum of the spacing of the characters before it.
float GetJustificationBefore(Span<const JustificationSpacing> spacing, int end);

} // namespace Rml
