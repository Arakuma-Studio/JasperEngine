---@class ConsoleCommandInfo
---@field name string
---@field description string
---@field usage string
---@field aliases string[]
---@field cheat boolean
---@field builtIn boolean
---@field args {name: string, type: string, optional: boolean, default?: string, min?: number, max?: number, choices?: string[]}[]
