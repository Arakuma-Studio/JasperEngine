"""Writes engine/core/render/LtcLut.h from the fitted GGX LTC tables of Heitz et al. 2016.

The tables are fit/results/ltc_1.dds and ltc_2.dds of github.com/selfshadow/ltc_code (BSD-2-Clause
with a request to cite the paper, recorded in NOTICE.md), at the commit below: two 64x64 RGBA16F
images. The header keeps their half floats bit for bit.

    python3 -I tools/gen_ltc_lut.py --source <clone of selfshadow/ltc_code at LTC_COMMIT>
"""
import argparse
import os
import struct
import sys

LTC_COMMIT = "31e5e96b54f98f33098f8503003119ba2231a1c6"
SIZE = 64
OUTPUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "engine", "core", "render", "LtcLut.h")


def read_dds(path):
    with open(path, "rb") as f:
        data = f.read()
    if data[:4] != b"DDS ":
        sys.exit(f"{path}: not a DDS file")
    header = struct.unpack("<31I", data[4:128])
    height, width, fourcc = header[2], header[3], header[20]
    # D3DFMT_A16B16G16R16F: four halves a texel, R first in memory
    if (width, height, fourcc) != (SIZE, SIZE, 113):
        sys.exit(f"{path}: expected a {SIZE}x{SIZE} A16B16G16R16F image, got {width}x{height} fourcc {fourcc}")
    count = SIZE * SIZE * 4
    payload = data[128:128 + count * 2]
    if len(payload) != count * 2:
        sys.exit(f"{path}: truncated")
    return struct.unpack(f"<{count}H", payload)


def emit(name, values):
    lines = [f"    static const uint16_t {name}[LTC_LUT_SIZE * LTC_LUT_SIZE * 4] = {{"]
    per_line = 16
    for i in range(0, len(values), per_line):
        lines.append("        " + ",".join(f"0x{v:04x}" for v in values[i:i + per_line]) + ",")
    lines.append("    };")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", required=True, help="a clone of selfshadow/ltc_code at LTC_COMMIT")
    parser.add_argument("--output", default=OUTPUT)
    args = parser.parse_args()

    ltc1 = read_dds(os.path.join(args.source, "fit", "results", "ltc_1.dds"))
    ltc2 = read_dds(os.path.join(args.source, "fit", "results", "ltc_2.dds"))

    text = f"""// (c) Eduardo Doria and contributors
// SPDX-License-Identifier: MIT
//
// Generated by tools/gen_ltc_lut.py from fit/results/ltc_1.dds and ltc_2.dds of
// github.com/selfshadow/ltc_code at {LTC_COMMIT}
// (BSD-2-Clause, see NOTICE.md). Do not edit.
//
// Real-Time Polygonal-Light Shading with Linearly Transformed Cosines. Eric Heitz, Jonathan Dupuy,
// Stephen Hill and David Neubelt. ACM Transactions on Graphics (Proceedings of ACM SIGGRAPH 2016)
// 35(4), 2016.

#ifndef LTC_LUT_H
#define LTC_LUT_H

#include <cstdint>

namespace jasperengine{{

    // The GGX fit, half floats, RGBA a texel, rows of increasing sqrt(1 - cos(theta_view)), columns
    // of increasing perceptual roughness:
    //   ltcLut1  the inverse matrix's terms m00, m02, m20, m22 (m11 = 1, the others 0)
    //   ltcLut2  x the BRDF's directional albedo, y its Fresnel share, z 0, w the horizon-clipped
    //            sphere form factor by (z * 0.5 + 0.5, |F|) of the polygon's vector form factor F
    constexpr int LTC_LUT_SIZE = {SIZE};
{emit("ltcLut1", ltc1)}
{emit("ltcLut2", ltc2)}

}}

#endif //LTC_LUT_H
"""
    with open(args.output, "w", newline="\n") as f:
        f.write(text)


if __name__ == "__main__":
    main()
