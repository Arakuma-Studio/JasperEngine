#!/usr/bin/env python3
"""Generates editor/window/widget/RcssProperties.h, the RCSS property names the code editor
offers as suggestions in CSS files and in HTML style="" attributes.

    tools/gen_rcss_properties.py [--check]

The names are read from RmlUi's property registrations
(engine/libs/rmlui/Source/Core/StyleSheetSpecification.cpp): every
`RegisterProperty(PropertyId::X, "name", ...)` and `RegisterShorthand(ShorthandId::X, "name", ...)`.
Re-run it after updating RmlUi. --check writes nothing and exits 1 if the header is stale.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "engine/libs/rmlui/Source/Core/StyleSheetSpecification.cpp"
OUTPUT = ROOT / "editor/window/widget/RcssProperties.h"

REGISTRATION = re.compile(r'\bRegister(?:Property|Shorthand)\s*\(\s*(?:PropertyId|ShorthandId)::\w+\s*,\s*"([^"]+)"')


def collect(source_text):
    names = sorted(set(REGISTRATION.findall(source_text)))
    if not names:
        sys.exit(f"no property registrations found in {SOURCE}")
    return names


def render(names):
    lines = [
        "// (c) Eduardo Doria and contributors",
        "// SPDX-License-Identifier: MIT",
        "",
        "// Generated by tools/gen_rcss_properties.py, do not edit.",
        "// RCSS property and shorthand names registered by RmlUi's StyleSheetSpecification.cpp",
        "",
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
        "namespace jasperengine::editor {",
        "",
        "    static const char* const kRcssProperties[] = {",
    ]
    lines += [f'        "{name}",' for name in names]
    lines += [
        "    };",
        "",
        "    static const size_t kRcssPropertyCount = sizeof(kRcssProperties) / sizeof(kRcssProperties[0]);",
        "",
        "} // namespace jasperengine::editor",
        "",
    ]
    return "\n".join(lines)


def main():
    header = render(collect(SOURCE.read_text(encoding="utf-8")))
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != header:
            print(f"{OUTPUT.relative_to(ROOT)} is stale: run tools/gen_rcss_properties.py")
            return 1
        return 0
    OUTPUT.write_text(header, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
