#!/usr/bin/env python3
"""Embed the sound essentials in the editor: writes a C++ header with the manifest text and
one byte array per clip. The root CMakeLists.txt runs it at
build time; editor/audio/SoundEssentials.cpp includes the header.

    python3 tools/sound-library/embed_essentials.py <essentials dir> <out header>

Standard library only. The build fails (exit 1) when the manifest does not list exactly the
clips on disk, or a clip's size or SHA-256 disagrees with the manifest: the editor must never
carry bytes other than the pinned ones."""

import hashlib
import json
import sys
from pathlib import Path

FORMAT = "jasperengine-sound-essentials"
BYTES_PER_LINE = 24


def fail(message: str) -> None:
    print(f"embed_essentials: {message}", file=sys.stderr)
    sys.exit(1)


def c_bytes(data: bytes, indent: str = "    ") -> str:
    lines = []
    for at in range(0, len(data), BYTES_PER_LINE):
        lines.append(indent + ",".join(f"0x{b:02x}" for b in data[at:at + BYTES_PER_LINE]) + ",")
    return "\n".join(lines)


def main(argv: list) -> int:
    if len(argv) != 3:
        fail("usage: embed_essentials.py <essentials dir> <out header>")
    root, out = Path(argv[1]), Path(argv[2])
    manifest_path = root / "manifest.json"
    try:
        manifest_bytes = manifest_path.read_bytes()
        manifest = json.loads(manifest_bytes.decode("utf-8"))
    except (OSError, ValueError) as e:
        fail(f"can't read {manifest_path}: {e}")
    if manifest.get("format") != FORMAT or manifest.get("version") != 2:
        fail(f"{manifest_path} is not a version 2 {FORMAT} manifest")
    clips = manifest.get("clips")
    if not isinstance(clips, list) or not clips:
        fail("the manifest lists no clips")

    on_disk = sorted(p.relative_to(root).as_posix() for p in root.rglob("*.ogg"))
    listed = sorted(c.get("path", "") for c in clips)
    if on_disk != listed:
        missing = sorted(set(listed) - set(on_disk))
        extra = sorted(set(on_disk) - set(listed))
        fail(f"the clips on disk differ from the manifest (missing: {missing}, not listed: {extra})")

    parts = [
        "// Generated by tools/sound-library/embed_essentials.py from editor/resources/sound-library/essentials.",
        "// Do not edit: the build regenerates it when the manifest or a clip changes.",
        "#pragma once",
        "",
        f"static const unsigned int sound_essentials_manifest_size = {len(manifest_bytes)};",
        "static const unsigned char sound_essentials_manifest[] = {",
        c_bytes(manifest_bytes),
        "    0x00};",
        "",
    ]
    entries = []
    for i, clip in enumerate(clips):
        path = clip.get("path", "")
        data = (root / path).read_bytes()
        if len(data) != clip.get("bytes"):
            fail(f"{path}: {len(data)} bytes, the manifest says {clip.get('bytes')}")
        digest = hashlib.sha256(data).hexdigest()
        if digest != clip.get("sha256"):
            fail(f"{path}: SHA-256 {digest}, the manifest says {clip.get('sha256')}")
        parts += [f"// {clip.get('id')}", f"static const unsigned char sound_essentials_clip_{i}[] = {{", c_bytes(data), "};", ""]
        entries.append(f'    {{"{path}", sound_essentials_clip_{i}, {len(data)}u}},')
    parts += [
        "struct SoundEssentialsFile { const char* path; const unsigned char* data; unsigned int size; };",
        f"static const unsigned int sound_essentials_file_count = {len(entries)};",
        "static const SoundEssentialsFile sound_essentials_files[] = {",
        *entries,
        "};",
        "",
    ]
    text = "\n".join(parts)
    out.parent.mkdir(parents=True, exist_ok=True)
    temporary = out.with_name(out.name + ".tmp")
    with open(temporary, "w", encoding="utf-8", newline="\n") as stream:
        stream.write(text)
    temporary.replace(out)
    print(f"embed_essentials: {len(entries)} clips, {sum(c['bytes'] for c in clips)} bytes -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
