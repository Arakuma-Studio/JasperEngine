# Writes tools/test-projects/noise/NoisePresetData.h from editor/resources/noisegraphs (T2 R41), so the
# noise test project holds every preset on targets whose build system embeds nothing:
#
#   python3 tools/noise/gen_test_project_presets.py [--check]

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = os.path.join(ROOT, "editor", "resources", "noisegraphs")
TARGET = os.path.join(ROOT, "tools", "test-projects", "noise", "NoisePresetData.h")
# MSVC's limit on one string literal is far above this; adjacent ones concatenate
PIECE = 8000


def generate():
    out = ["// (c) Eduardo Doria and contributors", "// SPDX-License-Identifier: MIT", "",
           "// Generated by tools/noise/gen_test_project_presets.py. Do not edit.", "",
           "#pragma once", "", "struct NoisePresetText { const char* id; const char* json; };", "",
           "static const NoisePresetText kNoisePresets[] = {"]
    for name in sorted(os.listdir(SOURCE)):
        if not name.endswith(".noisegraph"):
            continue
        with open(os.path.join(SOURCE, name), encoding="utf-8", newline="") as f:
            text = f.read()
        out.append('    {"%s",' % name[:-len(".noisegraph")])
        for start in range(0, len(text), PIECE):
            out.append('R"__P__(%s)__P__"' % text[start:start + PIECE])
        out.append("    },")
    out += ["    {nullptr, nullptr}", "};", ""]
    return "\n".join(out)


def main():
    text = generate()
    if "--check" in sys.argv:
        current = open(TARGET, encoding="utf-8", newline="").read() if os.path.exists(TARGET) else ""
        if current != text:
            print("tools/test-projects/noise/NoisePresetData.h is stale: run tools/noise/gen_test_project_presets.py")
            return 1
        return 0
    os.makedirs(os.path.dirname(TARGET), exist_ok=True)
    with open(TARGET, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
