def object_id(kind, key):
    return PREFIX + hashlib.sha1((kind + ":" + key).encode()).hexdigest()[:16].upper()


def inc(path):
    return '"$(SRCROOT)/../../libs/%s"' % path


def cmake_sources(cmake_file, list_name=None, call="add_library", extensions=r"c|cc|cpp"):
    """The source paths of a set(<list_name> ...) or of the add_library(... STATIC ...) call."""
    text = open(cmake_file, encoding="utf-8").read()
    text = re.sub(r"#[^\n]*", "", text)
    if list_name:
        m = re.search(r"set\(\s*%s\s+(.*?)\)" % re.escape(list_name), text, re.S)
    else:
        m = re.search(r"%s\(\s*\w+\s+STATIC\s+(.*?)\)" % call, text, re.S)
    if not m:
        raise SystemExit("no source list in " + cmake_file)
    return [token for token in m.group(1).split() if re.search(r"\.(%s)$" % extensions, token)]


