def dav1d_wrappers():
    """{relative wrapper path: content} for every template and bit depth."""
    templates = cmake_sources(os.path.join(LIBS, "dav1d", "CMakeLists.txt"), "DAV1D_TEMPLATE_SOURCES")
    out = {}
    for template in templates:
        stem = os.path.splitext(os.path.basename(template))[0]
        for depth in (8, 16):
            out["bitdepth/%s_%d.c" % (stem, depth)] = (
                "// Generated by tools/htmlui/xcode_add_video_libs.py for the Xcode targets: %s with\n"
                "// BITDEPTH %d (CMake compiles the template twice through OBJECT libraries instead).\n"
                "#define BITDEPTH %d\n"
                "#include \"%s\"\n" % (template, depth, depth, template))
    # the arm64 .S files under names no C file has (msac.S, refmvs.S next to msac.c, refmvs.c:
    # one object name each in a target)
    for source in cmake_sources(os.path.join(LIBS, "dav1d", "CMakeLists.txt"), "DAV1D_ASM_AARCH64", extensions="S"):
        stem = os.path.splitext(os.path.basename(source))[0]
        out["xcode/aarch64_%s.S" % stem] = (
            "// Generated by tools/htmlui/xcode_add_video_libs.py for the Xcode targets: %s under a\n"
            "// name no C file of dav1d has (Xcode names objects by the file name).\n"
            "#include \"%s\"\n" % (source, source))
    for name, arch, condition in (("x86", "x86-64", "ARCH_X86_64"), ("arm", "arm64", "ARCH_AARCH64 || ARCH_ARM")):
        out["xcode/cpu_%s.c" % name] = (
            "// Generated by tools/htmlui/xcode_add_video_libs.py for the Xcode targets: src/%s/cpu.c, the\n"
            "// CPU feature detection of dav1d's %s asm, in that architecture's slices only (CMake\n"
            "// compiles it for its target alone).\n"
            "#include \"config.h\"\n"
            "// config.h must be dav1d's: another library's (through Xcode's header map, which the targets\n"
            "// turn off) leaves dav1d without a bit depth (it decodes nothing) and its asm unassembled\n"
            "#ifndef DAV1D_ENGINE_CONFIG_H\n"
            "#error \"config.h is not engine/libs/dav1d/config/config.h: is USE_HEADERMAP = NO on the dav1d targets?\"\n"
            "#endif\n"
            "#if (%s) && HAVE_ASM\n"
            "#include \"src/%s/cpu.c\"\n"
            "#endif\n" % (name, arch, condition, name))
    return out


def dav1d_asm():
    """(the arm64 wrappers, the NASM files)"""
    cmake = os.path.join(LIBS, "dav1d", "CMakeLists.txt")
    arm64 = ["xcode/aarch64_%s.S" % os.path.splitext(os.path.basename(source))[0]
             for source in cmake_sources(cmake, "DAV1D_ASM_AARCH64", extensions="S")]
    return arm64, cmake_sources(cmake, "DAV1D_ASM_X86_64", extensions="asm")


# the build rule of the NASM files (x86-64 slices): Mach-O, dav1d's include roots and prefix
NASM_SCRIPT = (
    'NASM=$(command -v nasm || true)\n'
    'for candidate in /opt/homebrew/bin/nasm /usr/local/bin/nasm; do\n'
    '  if [ -z "$NASM" ] && [ -x "$candidate" ]; then NASM="$candidate"; fi\n'
    'done\n'
    'if [ -z "$NASM" ]; then echo "error: dav1d\'s x86-64 asm needs NASM 2.14 or newer (brew install nasm)"; exit 1; fi\n'
    'mkdir -p "$DERIVED_FILE_DIR/$CURRENT_ARCH"\n'
    'exec "$NASM" -f macho64 -DDAV1D_NASM_PREFIX -I"$SRCROOT/../../libs/dav1d/src/" -I"$SRCROOT/../../libs/dav1d/config/" '
    '-o "$DERIVED_FILE_DIR/$CURRENT_ARCH/$INPUT_FILE_BASE.nasm.o" "$INPUT_FILE_PATH"\n')
EXCLUDED = (('"EXCLUDED_SOURCE_FILE_NAMES[arch=arm64]"', '"*.asm"'), ('"EXCLUDED_SOURCE_FILE_NAMES[arch=x86_64]"', '"*.S"'))


