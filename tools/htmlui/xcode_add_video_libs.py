def add_library_files(project, lib):
    def group_id(directory):
        return object_id("group", lib["dir"] + "/" + directory)

    files = lib["sources"]
    directories = set()
    for path in files:
        parts = path.split("/")[:-1]
        for depth in range(len(parts) + 1):
            directories.add("/".join(parts[:depth]))
    for directory in sorted(directories, key=lambda d: (d.count("/") if d else -1, d)):
        gid = group_id(directory)
        name = directory.split("/")[-1] if directory else lib["dir"]
        project.add_object("PBXGroup", gid, lx.group_block(gid, name))
        if directory:
            parent = group_id("/".join(directory.split("/")[:-1]))
            project.add_to_list(parent, "children", "\t\t\t\t%s /* %s */," % (gid, name))
        else:
            project.add_to_list(lx.LIBS_GROUP, "children", "\t\t\t\t%s /* %s */," % (gid, name), sort_name=name)

    for path in files:
        name = path.split("/")[-1]
        directory = "/".join(path.split("/")[:-1])
        ref = object_id("ref", lib["dir"] + "/" + path)
        file_type = {".cc": "sourcecode.cpp.cpp", ".cpp": "sourcecode.cpp.cpp", ".S": "sourcecode.asm",
                     ".asm": "sourcecode.asm.asm"}.get(os.path.splitext(name)[1], "sourcecode.c.c")
        project.add_object("PBXFileReference", ref, [
            "\t\t%s /* %s */ = {isa = PBXFileReference; fileEncoding = 4; lastKnownFileType = %s; path = %s; sourceTree = \"<group>\"; };"
            % (ref, name, file_type, name)])
        project.add_to_list(group_id(directory), "children", "\t\t\t\t%s /* %s */," % (ref, name))

    for platform in PLATFORMS:
        sources_phase = object_id("sources", lib["name"] + ":" + platform)
        for path in files:
            name = path.split("/")[-1]
            ref = object_id("ref", lib["dir"] + "/" + path)
            build = object_id("src-" + platform, lib["dir"] + "/" + path)
            project.add_object("PBXBuildFile", build, [
                "\t\t%s /* %s in Sources */ = {isa = PBXBuildFile; fileRef = %s /* %s */; };" % (build, name, ref, name)])
            project.add_to_list(sources_phase, "files", "\t\t\t\t%s /* %s in Sources */," % (build, name))


def link_libraries(project, lib, portal):
    for platform in PLATFORMS:
        key = lib["name"] + ":" + platform
        name = "%s-%s" % (lib["name"], platform)
        product_name = "lib%s.a" % name
        target = object_id("target", key)
        product = object_id("product", key)
        lunasvg_target = project.target_by_name("lunasvg-" + platform)

        link_phases = []
        for i, line in enumerate(project.lines):
            if re.match(r"^\t\t\t\t[0-9A-F]{24} /\* liblunasvg-%s\.a in Frameworks \*/,$" % platform, line):
                link_phases.append(project.owner(i)[0])
        for phase in link_phases:
            build = object_id("link-" + key, phase)
            project.add_object("PBXBuildFile", build, [
                "\t\t%s /* %s in Frameworks */ = {isa = PBXBuildFile; fileRef = %s /* %s */; };" % (build, product_name, product, product_name)])
            project.add_to_list(phase, "files", "\t\t\t\t%s /* %s in Frameworks */," % (build, product_name),
                                after="liblunasvg-%s.a in Frameworks */," % platform)

        lunasvg_dependencies = set()
        for i, line in enumerate(project.lines):
            if line.startswith("\t\t\ttarget = " + lunasvg_target + " "):
                lunasvg_dependencies.add(project.owner(i)[0])
        dependents = []
        for i, line in enumerate(project.lines):
            m = re.match(r"^\t\t\t\t([0-9A-F]{24}) /\* PBXTargetDependency \*/,$", line)
            if m and m.group(1) in lunasvg_dependencies:
                dependents.append((project.owner(i)[0], m.group(1)))
        for dependent, lunasvg_dependency in dependents:
            proxy = object_id("proxy-" + key, dependent)
            dependency = object_id("dependency-" + key, dependent)
            project.add_object("PBXContainerItemProxy", proxy, [
                "\t\t%s /* PBXContainerItemProxy */ = {" % proxy,
                "\t\t\tisa = PBXContainerItemProxy;",
                "\t\t\tcontainerPortal = %s /* Project object */;" % portal,
                "\t\t\tproxyType = 1;",
                "\t\t\tremoteGlobalIDString = %s;" % target,
                "\t\t\tremoteInfo = \"%s\";" % name,
                "\t\t};",
            ])
            project.add_object("PBXTargetDependency", dependency, [
                "\t\t%s /* PBXTargetDependency */ = {" % dependency,
                "\t\t\tisa = PBXTargetDependency;",
                "\t\t\ttarget = %s /* %s */;" % (target, name),
                "\t\t\ttargetProxy = %s /* PBXContainerItemProxy */;" % proxy,
                "\t\t};",
            ])
            project.add_to_list(dependent, "dependencies", "\t\t\t\t%s /* PBXTargetDependency */," % dependency,
                                after=lunasvg_dependency + " /* PBXTargetDependency */,")


def engine_configurations(project):
    owners = {}
    for line in project.lines:
        m = lx.OBJECT_LINE.match(line)
        if m and m.group(2).startswith("Build configuration list for "):
            open_, close = project.list_span(m.group(1), "buildConfigurations")
            for entry in project.lines[open_ + 1:close]:
                owners[entry.strip().split(" ")[0]] = re.search(r'"(.*)"', m.group(2)).group(1)
    configs = []
    for i, line in enumerate(project.lines):
        if line.strip() == LUNASVG_INCLUDE + ",":
            config = project.owner(i)[0]
            if not SKIP_CONFIG_OWNERS.match(owners.get(config, "")):
                configs.append(config)
    return configs


def pbx_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def add_dav1d_asm(project):
    """dav1d's asm settings on its targets: DAV1D_ASM, the per-architecture exclusions, the NASM
    build rule (created configurations get them too: this runs after the targets are made)."""
    if "/* Begin PBXBuildRule section */" not in project.lines:
        index = project.lines.index("/* End PBXBuildFile section */") + 1
        project.lines[index:index] = ["", "/* Begin PBXBuildRule section */", "/* End PBXBuildRule section */"]
        project.added.append("PBXBuildRule section")
    for platform in PLATFORMS:
        name = "dav1d-" + platform
        for config in project.configurations('Build configuration list for PBXNativeTarget "%s"' % name).values():
            open_, close = project.list_span(config, "GCC_PREPROCESSOR_DEFINITIONS", "\t\t\t\t")
            if "DAV1D_ASM," not in [line.strip() for line in project.lines[open_ + 1:close]]:
                project.lines.insert(close, "\t\t\t\t\tDAV1D_ASM,")
                project.added.append("DAV1D_ASM in " + config)
            first, last = project.block(config)
            for key, value in EXCLUDED:
                if not any(line.strip().startswith(key + " =") for line in project.lines[first:last]):
                    at = next(i for i in range(first, last) if project.lines[i].strip().startswith("GCC_C_LANGUAGE_STANDARD"))
                    project.lines.insert(at, "\t\t\t\t%s = %s;" % (key, value))
                    project.added.append(key + " in " + config)
                    first, last = project.block(config)
        rule = object_id("buildrule", "dav1d:" + platform)
        project.add_object("PBXBuildRule", rule, [
            "\t\t%s /* PBXBuildRule */ = {" % rule,
            "\t\t\tisa = PBXBuildRule;",
            "\t\t\tcompilerSpec = com.apple.compilers.proxy.script;",
            "\t\t\tfilePatterns = \"*.asm\";",
            "\t\t\tfileType = pattern.proxy;",
            "\t\t\tinputFiles = (",
            "\t\t\t);",
            "\t\t\tisEditable = 1;",
            "\t\t\tname = \"dav1d NASM\";",
            "\t\t\toutputFiles = (",
            "\t\t\t\t\"$(DERIVED_FILE_DIR)/$(CURRENT_ARCH)/$(INPUT_FILE_BASE).nasm.o\",",
            "\t\t\t);",
            "\t\t\tscript = %s;" % pbx_string(NASM_SCRIPT),
            "\t\t};",
        ])
        project.add_to_list(project.target_by_name(name), "buildRules", "\t\t\t\t%s /* PBXBuildRule */," % rule)


def disable_headermaps(project, libs):
    """USE_HEADERMAP = NO in the libraries' configurations: their quoted includes resolve through
    their own search paths, as CMake's do. Xcode's project header map (-iquote, searched before
    them) maps a header's file name to any header of that name in the project: dav1d's
    "config.h" became engine/libs/thorvg/config/config.h (no ARCH_AARCH64, CONFIG_8BPC, ...: the
    asm did not assemble and the C decoder had no bit depth)."""
    for lib in libs:
        for platform in PLATFORMS:
            name = "%s-%s" % (lib["name"], platform)
            for config in project.configurations('Build configuration list for PBXNativeTarget "%s"' % name).values():
                first, last = project.block(config)
                settings = [i for i in range(first, last) if re.match(r"^\t\t\t\t[^\t]", project.lines[i])]
                if any(project.lines[i].strip().startswith("USE_HEADERMAP =") for i in settings):
                    continue
                # Xcode keeps the keys sorted: before the first key after it, or at the end
                keys = [(project.lines[i].strip().strip('"'), i) for i in settings]
                at = next((i for key, i in keys if key > "USE_HEADERMAP"), None)
                if at is None:
                    at = next(i for i in range(first, last) if project.lines[i] == "\t\t\t};")
                project.lines.insert(at, "\t\t\t\tUSE_HEADERMAP = NO;")
                project.added.append("USE_HEADERMAP = NO in " + config)


def add_public_interface(project, libs):
    configs = engine_configurations(project)
    for config in configs:
        for lib in libs:
            include = lib["public_include"]
            open_, close = project.list_span(config, "HEADER_SEARCH_PATHS", "\t\t\t\t")
            if not any(line.strip() == include + "," for line in project.lines[open_ + 1:close]):
                position = next(i for i in range(open_ + 1, close) if project.lines[i].strip() == LUNASVG_INCLUDE + ",")
                project.lines.insert(position + 1, "\t\t\t\t\t%s," % include)
                project.added.append("%s search path in %s" % (lib["name"], config))
            if lib["public_define"]:
                define = quoted(lib["public_define"]) + ","
                open_, close = project.list_span(config, "GCC_PREPROCESSOR_DEFINITIONS", "\t\t\t\t")
                if define not in [line.strip() for line in project.lines[open_ + 1:close]]:
                    project.lines.insert(close, "\t\t\t\t\t%s" % define)
                    project.added.append("%s define in %s" % (lib["name"], config))
    return configs


