def quoted(value):
    return '"%s"' % value if re.search(r"[^A-Za-z0-9_]", value) else value


def clone_configuration(project, template_id, new_id, name, lib):
    first, last = project.block(template_id)
    out = ["\t\t%s /* %s */ = {" % (new_id, name)]
    i = first + 1
    while i < last:
        line = project.lines[i]
        key = line.strip().split(" ")[0]
        if key in CXX_ONLY and not lib["cxx"]:
            i += 1
            continue
        if key == "GCC_C_LANGUAGE_STANDARD" and lib["c"]:
            out.append("\t\t\t\tGCC_C_LANGUAGE_STANDARD = %s;" % lib["c"])
            i += 1
            continue
        if key in ("GCC_PREPROCESSOR_DEFINITIONS", "HEADER_SEARCH_PATHS") and line.rstrip().endswith("= ("):
            if key == "GCC_PREPROCESSOR_DEFINITIONS":
                values = ['"$(inherited)"'] + [quoted(d) for d in lib["defines"]]
            else:
                values = lib["includes"]
            out.append(line)
            out.extend("\t\t\t\t\t%s," % value for value in values)
            while project.lines[i].strip() != ");":
                i += 1
            out.append(project.lines[i])
            i += 1
            continue
        out.append(line)
        i += 1
    out.append("\t\t};")
    return out


def keep_headermap_off(project, lib):
    """USE_HEADERMAP = NO in every configuration of the library's targets (lib["headermap"] False)"""
    if lib.get("headermap", True):
        return
    for platform in PLATFORMS:
        name = "%s-%s" % (lib["name"], platform)
        configs = project.configurations('Build configuration list for PBXNativeTarget "%s"' % name)
        for config_name, cid in sorted(configs.items()):
            first, last = project.block(cid)
            settings = project.lines[first:last]
            if any(line.strip() == "USE_HEADERMAP = NO;" for line in settings):
                continue
            # the end of buildSettings: the last "};" before the configuration's name
            end = max(i for i in range(first, last) if project.lines[i] == "\t\t\t};")
            project.lines.insert(end, "\t\t\t\tUSE_HEADERMAP = NO;")
            project.added.append("no header map in %s %s" % (name, config_name))


