def add_media_sources(project):
    group = object_id("group", "@media")
    if not project.has(group):
        index = next(i for i, line in enumerate(project.lines) if base.HTMLUI_GROUP in line)
        project.lines[index:index] = lx.group_block(group, "media")
        project.added.append(group)
        project.add_to_list("48544D4C0000000000000047", "children", "\t\t\t\t%s /* media */," % group)
    names = sorted(n for n in os.listdir(MEDIA) if n.endswith((".cpp", ".h")))
    for name in names:
        ref = object_id("ref", "media/" + name)
        is_header = name.endswith(".h")
        file_type = "sourcecode.c.h" if is_header else "sourcecode.cpp.cpp"
        project.add_object("PBXFileReference", ref, [
            "\t\t%s /* %s */ = {isa = PBXFileReference; fileEncoding = 4; lastKnownFileType = %s; path = %s; sourceTree = \"<group>\"; };"
            % (ref, name, file_type, name)])
        project.add_to_list(group, "children", "\t\t\t\t%s /* %s */," % (ref, name))
        if is_header:
            build = object_id("hdr", "media/" + name)
            project.add_object("PBXBuildFile", build, [
                "\t\t%s /* %s in Headers */ = {isa = PBXBuildFile; fileRef = %s /* %s */; };" % (build, name, ref, name)])
            phase = owner_of_entry(project, base.HEADERS_ANCHOR)
            project.add_to_list(phase, "files", "\t\t\t\t%s /* %s in Headers */," % (build, name))
        else:
            for index, anchor in enumerate(base.SOURCES_ANCHORS):
                build = object_id("src%d" % (index + 1), "media/" + name)
                project.add_object("PBXBuildFile", build, [
                    "\t\t%s /* %s in Sources */ = {isa = PBXBuildFile; fileRef = %s /* %s */; };" % (build, name, ref, name)])
                project.add_to_list(owner_of_entry(project, anchor), "files", "\t\t\t\t%s /* %s in Sources */," % (build, name))
    return len(names)


def owner_of_entry(project, entry):
    index = next(i for i, line in enumerate(project.lines) if line.strip() == entry.strip())
    return project.owner(index)[0]


def add_sibling_source(project, sibling, name):
    """`name` next to the existing source `sibling`: the same group and Sources phases."""
    sibling_ref = None
    for line in project.lines:
        m = re.match(r"^\t\t([0-9A-F]{24}) /\* %s \*/ = \{isa = PBXFileReference;" % re.escape(sibling), line)
        if m:
            sibling_ref = m.group(1)
    if sibling_ref is None:
        raise SystemExit("not in the Xcode project: " + sibling)
    ref = object_id("ref", "binding/" + name)
    project.add_object("PBXFileReference", ref, [
        "\t\t%s /* %s */ = {isa = PBXFileReference; fileEncoding = 4; lastKnownFileType = sourcecode.cpp.cpp; path = %s; sourceTree = \"<group>\"; };"
        % (ref, name, name)])
    groups = [project.owner(i)[0] for i, line in enumerate(project.lines)
              if line.strip() == "%s /* %s */," % (sibling_ref, sibling)]
    for gid in groups:
        project.add_to_list(gid, "children", "\t\t\t\t%s /* %s */," % (ref, name), after="/* %s */," % sibling)
    sibling_builds = [m.group(1) for m in (re.match(r"^\t\t([0-9A-F]{24}) /\* %s in Sources \*/ = \{isa = PBXBuildFile; fileRef = %s "
                                                    % (re.escape(sibling), sibling_ref), line) for line in project.lines) if m]
    for number, sibling_build in enumerate(sibling_builds):
        build = object_id("src%d" % (number + 1), "binding/" + name)
        project.add_object("PBXBuildFile", build, [
            "\t\t%s /* %s in Sources */ = {isa = PBXBuildFile; fileRef = %s /* %s */; };" % (build, name, ref, name)])
        phase = owner_of_entry(project, "%s /* %s in Sources */," % (sibling_build, sibling))
        project.add_to_list(phase, "files", "\t\t\t\t%s /* %s in Sources */," % (build, name),
                            after="/* %s in Sources */," % sibling)
    return len(sibling_builds)


def write_wrappers(check):
    """dav1d's bit-depth wrappers: the missing or different ones (written unless check)."""
    stale = []
    for rel, content in dav1d_wrappers().items():
        path = os.path.join(LIBS, "dav1d", rel)
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current != content:
            stale.append(rel)
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(content)
    return stale


def main():
    check = "--check" in sys.argv
    stale = write_wrappers(check)
    with open(PROJECT, encoding="utf-8") as f:
        text = f.read()
    project = lx.Project(text.split("\n"))
    portal = next(line for line in project.lines if line.startswith("\trootObject = ")).split()[2]
    libs = libraries()
    for lib in libs:
        add_library_targets(project, lib, portal)
        keep_headermap_off(project, lib)
        add_library_files(project, lib)
        link_libraries(project, lib, portal)
    configs = add_public_interface(project, libs)
    disable_headermaps(project, libs)
    add_dav1d_asm(project)
    media = add_media_sources(project)
    phases = add_sibling_source(project, "HtmlUIClassesLua.cpp", "HtmlUIMediaLua.cpp")

    counts = project.defined()
    duplicates = [oid for oid, count in counts.items() if count > 1]
    if duplicates:
        raise SystemExit("duplicate object ids: " + ", ".join(duplicates))

    summary = ", ".join("%s %d" % (lib["name"], len(lib["sources"])) for lib in libs)
    summary += " sources per target; %d media files; %d engine configurations; binding in %d phases" % (media, len(configs), phases)
    if not project.added and not stale:
        print("Xcode project has the video libraries (" + summary + ")")
        return 0
    if check:
        print("the video libraries are missing from the Xcode project (%d changes, %d dav1d wrappers); "
              "run tools/htmlui/xcode_add_video_libs.py" % (len(project.added), len(stale)))
        return 1
    with open(PROJECT, "w", encoding="utf-8") as f:
        f.write("\n".join(project.lines))
    print("added the video libraries to the Xcode project: %d changes, %d dav1d wrappers written (%s)"
          % (len(project.added), len(stale), summary))
    return 0


if __name__ == "__main__":
    sys.exit(main())
