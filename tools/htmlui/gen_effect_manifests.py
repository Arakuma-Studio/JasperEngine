#!/usr/bin/env python3
# Writes engine/core/htmlui/effects/BuiltinEffectManifests.gen.cpp: the manifest of every
# built-in UI effect (phase 5), read from engine/shaderlib/effects/<name>.frag. A shipped game
# has no shader sources (only the compiled variants), so the effect registry reads the
# manifests from this table. Each entry is the file's #version line, its manifest block (the
# "// @" lines right after it) and its main include lines (main_paint/main_filter, and main_step
# of a stateful effect), which is all the registry parses and
# checks. Files whose name starts with '_' are internal passes and are skipped.
#
#   python3 tools/htmlui/gen_effect_manifests.py [--check]
#
# --check exits 1 when the generated file is stale (nothing is written). The file is never
# merged by hand: on a conflict, run this script again.

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
EFFECTS = os.path.join(ROOT, "engine", "shaderlib", "effects")
OUTPUT = os.path.join(ROOT, "engine", "core", "htmlui", "effects", "BuiltinEffectManifests.gen.cpp")

MAIN_INCLUDE = re.compile(r'^\s*#include\s+"effects/lib/main_(paint|filter|step)\.glsl"\s*$')


def manifest_of(path):
    with open(path, encoding="utf-8") as f:
        lines = f.read().replace("\r", "").split("\n")
    out = []
    i = 0
    while i < len(lines) and not lines[i].strip():
        i += 1
    if i >= len(lines) or not lines[i].strip().startswith("#version"):
        raise SystemExit("%s: an effect file starts with #version 450" % path)
    out.append(lines[i].strip())
    i += 1
    while i < len(lines):
        stripped = lines[i].strip()
        if not stripped.startswith("//") or not stripped[2:].strip().startswith("@"):
            break
        out.append(lines[i].rstrip())
        i += 1
    if len(out) == 1:
        raise SystemExit("%s: no manifest after #version 450" % path)
    mains = [line.strip() for line in lines if MAIN_INCLUDE.match(line)]
    # the registry checks there is exactly one, matching the kind: keep them all
    out.extend(mains)
    return out


def c_string(line):
    return '"' + line.replace("\\", "\\\\").replace('"', '\\"') + '\\n"'


def generate():
    names = sorted(name for name in os.listdir(EFFECTS)
                   if name.endswith(".frag") and not name.startswith("_") and os.path.isfile(os.path.join(EFFECTS, name)))
    parts = [
        "// (c) Eduardo Doria and contributors\n",
        "// SPDX-License-Identifier: MIT\n",
        "\n",
        "// Generated by tools/htmlui/gen_effect_manifests.py from engine/shaderlib/effects/*.frag. Do not edit:\n",
        "// run the script again (it is never merged by hand).\n",
        "\n",
        '#include "EffectRegistry.h"\n',
        "\n",
        "namespace {\n",
        "\n",
        "    const jasperengine::htmlui::BuiltinEffectSource kSources[] = {\n",
    ]
    for name in names:
        lines = manifest_of(os.path.join(EFFECTS, name))
        parts.append("        {\"effects/%s\",\n" % name)
        for index, line in enumerate(lines):
            end = "},\n" if index == len(lines) - 1 else "\n"
            parts.append("         %s%s" % (c_string(line), end))
    parts += [
        "    };\n",
        "\n",
        "}\n",
        "\n",
        "const jasperengine::htmlui::BuiltinEffectSource* jasperengine::htmlui::builtinEffectSources(size_t& count){\n",
        "    count = sizeof(kSources) / sizeof(kSources[0]);\n",
        "    return kSources;\n",
        "}\n",
    ]
    if not names:
        raise SystemExit("no effects in " + EFFECTS)
    return "".join(parts)


def main():
    check = "--check" in sys.argv[1:]
    text = generate()
    current = open(OUTPUT, encoding="utf-8").read() if os.path.exists(OUTPUT) else None
    if check:
        if current != text:
            print("%s is stale: run tools/htmlui/gen_effect_manifests.py" % os.path.relpath(OUTPUT, ROOT))
            sys.exit(1)
        print("BuiltinEffectManifests.gen.cpp is current")
        return
    if current != text:
        with open(OUTPUT, "w", encoding="utf-8") as f:
            f.write(text)
        print("wrote %s" % os.path.relpath(OUTPUT, ROOT))
    else:
        print("BuiltinEffectManifests.gen.cpp is current")


if __name__ == "__main__":
    main()
