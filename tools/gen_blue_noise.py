#!/usr/bin/env python3
"""Generate engine/core/render/BlueNoise64.h: a 64x64 tileable blue-noise threshold map (R8).

The atmosphere raymarches (volumetric fog, clouds) offset their first step by it, so every
pixel's jitter is static (no frame index) and its error is high-frequency, which the denoise
pass and the bilateral upsample remove (docs/specs/S12-atmosphere.md R12).

Void-and-cluster (Ulichney, "The void-and-cluster method for dither array generation", 1993)
on a torus with a Gaussian filter of sigma 1.5: an initial binary pattern is relaxed by moving
its tightest cluster into its largest void until stable; its points are then ranked by removing
tightest clusters, the rest by filling largest voids. The rank of each texel, scaled to
0..255, is the map. Deterministic (fixed seed); pure Python, about a minute.

    python3 tools/gen_blue_noise.py            # writes the header
    python3 tools/gen_blue_noise.py --check    # fails if the committed header differs
"""

import argparse
import math
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "engine/core/render/BlueNoise64.h"
SIZE = 64
SIGMA = 1.5
SEED = 1337
INITIAL_DENSITY = 0.1


def gaussian_kernel():
    """Toroidal Gaussian weights by (dx, dy) offset, flattened."""
    kernel = [0.0] * (SIZE * SIZE)
    for dy in range(SIZE):
        wy = min(dy, SIZE - dy)
        for dx in range(SIZE):
            wx = min(dx, SIZE - dx)
            kernel[dy * SIZE + dx] = math.exp(-(wx * wx + wy * wy) / (2.0 * SIGMA * SIGMA))
    return kernel


class Field:
    """A binary pattern and the filtered energy of its ones (or of its zeros)."""

    def __init__(self, kernel, pattern):
        self.kernel = kernel
        self.pattern = list(pattern)
        self.energy = [0.0] * (SIZE * SIZE)
        for p, bit in enumerate(self.pattern):
            if bit:
                self.splat(p, 1.0)

    def splat(self, p, sign):
        px, py = p % SIZE, p // SIZE
        kernel = self.kernel
        energy = self.energy
        for y in range(SIZE):
            row = ((y - py) % SIZE) * SIZE
            base = y * SIZE
            for x in range(SIZE):
                energy[base + x] += sign * kernel[row + (x - px) % SIZE]

    def set(self, p, bit):
        if self.pattern[p] != bit:
            self.pattern[p] = bit
            self.splat(p, 1.0 if bit else -1.0)

    def tightest_cluster(self):
        """The one with the most energy (ties: the lowest index)."""
        best, best_p = -1.0, -1
        for p, bit in enumerate(self.pattern):
            if bit and self.energy[p] > best:
                best, best_p = self.energy[p], p
        return best_p

    def largest_void(self):
        """The zero with the least energy (ties: the lowest index)."""
        best, best_p = float("inf"), -1
        for p, bit in enumerate(self.pattern):
            if not bit and self.energy[p] < best:
                best, best_p = self.energy[p], p
        return best_p


def void_and_cluster():
    kernel = gaussian_kernel()
    count = SIZE * SIZE
    rng = random.Random(SEED)
    ones = int(count * INITIAL_DENSITY)
    initial = [1] * ones + [0] * (count - ones)
    rng.shuffle(initial)

    # relax the initial pattern
    field = Field(kernel, initial)
    while True:
        cluster = field.tightest_cluster()
        field.set(cluster, 0)
        void = field.largest_void()
        if void == cluster:
            field.set(cluster, 1)
            break
        field.set(void, 1)
    prototype = list(field.pattern)

    rank = [0] * count
    # phase 1: rank the prototype's ones, tightest clusters last
    field = Field(kernel, prototype)
    for r in range(ones - 1, -1, -1):
        cluster = field.tightest_cluster()
        field.set(cluster, 0)
        rank[cluster] = r
    # phase 2: fill the largest voids up to half the texels
    field = Field(kernel, prototype)
    r = ones
    while r < count // 2:
        void = field.largest_void()
        field.set(void, 1)
        rank[void] = r
        r += 1
    # phase 3: the zeros left, as clusters of the inverted pattern
    inverted = Field(kernel, [0 if bit else 1 for bit in field.pattern])
    while r < count:
        cluster = inverted.tightest_cluster()
        inverted.set(cluster, 0)
        rank[cluster] = r
        r += 1
    return [rank[p] * 256 // count for p in range(count)]


def header(values):
    lines = [
        "// (c) Eduardo Doria and contributors",
        "// SPDX-License-Identifier: MIT",
        "//",
        "// Generated by tools/gen_blue_noise.py (void-and-cluster, 64x64, sigma 1.5, seed 1337). Do not edit.",
        "",
        "#ifndef BLUE_NOISE_64_H",
        "#define BLUE_NOISE_64_H",
        "",
        "#include <cstdint>",
        "",
        "namespace jasperengine{",
        "",
        "    // a tileable 64x64 blue-noise threshold map, each of 0..255 used 16 times, rows top first",
        "    constexpr int BLUE_NOISE_64_SIZE = 64;",
        "    static const uint8_t blueNoise64[BLUE_NOISE_64_SIZE * BLUE_NOISE_64_SIZE] = {",
    ]
    for y in range(SIZE):
        row = values[y * SIZE:(y + 1) * SIZE]
        lines.append("        " + ",".join(str(v) for v in row) + ",")
    lines += ["    };", "", "}", "", "#endif // BLUE_NOISE_64_H", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="compare with the committed header instead of writing it")
    args = parser.parse_args()
    text = header(void_and_cluster())
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print(f"{OUTPUT} is out of date: run tools/gen_blue_noise.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT} is current")
        return 0
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
