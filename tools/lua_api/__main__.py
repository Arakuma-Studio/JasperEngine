"""python3 -m lua_api (tools/ on PYTHONPATH):

    extract   --binding-dir B --core-dir C --json lua-api.json
    emit      --json lua-api.json [--stubs-header H] [--stubs-dir D] [--suggestions-header S]
              [--markdown M] [--data-header DH]
    all       --binding-dir B --core-dir C --json lua-api.json [the emit outputs]   (what CMake runs)
    doctest   [--json lua-api.json] [--root REPO] [files...]                       (see doctest.py)

--data-header writes a C++ header with the JSON and the Markdown as string literals (the editor's
jasper://lua-api resource, `doc lua-api-reference`, <project>/.jasperengine/engine-api/lua-api.json).
"""

import argparse
import os
import sys
import time

from . import extract as ex
from . import markdown, stubs, suggestions


def _data_header(api, md, path):
    import json
    text_json = json.dumps(api, separators=(',', ':'), ensure_ascii=False)
    out = ['// Auto-generated by tools/lua_api from lua-api.json - DO NOT EDIT', '#pragma once', '',
           'namespace jasperengine::editor::luaapi {', '']
    for name, text in (('json', text_json + '\n'), ('markdown', md)):
        out.append(f'static const char* const {name}Parts[] = {{')
        for part in stubs.c_string_literals(text):
            out.append('    ' + '\n    '.join(part) + ',')
        out.append('};')
        out.append(f'static const unsigned int {name}PartCount = sizeof({name}Parts) / sizeof({name}Parts[0]);')
        out.append('')
    out.append(f'static const char* const apiHash = "{api["hash"]}";')
    out.append('')
    out.append('} // namespace jasperengine::editor::luaapi')
    out.append('')
    ex.write_if_changed(path, '\n'.join(out))


def _emit(api, args):
    if args.stubs_header or args.stubs_dir:
        if not args.stubs_header:
            raise SystemExit('--stubs-dir needs --stubs-header')
        stubs.write_stubs(api, args.stubs_header, args.stubs_dir)
    if args.suggestions_header:
        suggestions.write_header(api, args.suggestions_header)
    md = markdown.reference(api) if (args.markdown or args.data_header) else None
    if args.markdown:
        ex.write_if_changed(args.markdown, md)
    if args.data_header:
        _data_header(api, md, args.data_header)


def main(argv=None):
    ap = argparse.ArgumentParser(prog='lua_api', description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest='command', required=True)
    for name in ('extract', 'emit', 'all'):
        sp = sub.add_parser(name)
        if name != 'emit':
            sp.add_argument('--binding-dir', required=True)
            sp.add_argument('--core-dir', required=True)
            sp.add_argument('--engine-version', default='')
        sp.add_argument('--json', required=True)
        if name != 'extract':
            sp.add_argument('--stubs-header')
            sp.add_argument('--stubs-dir')
            sp.add_argument('--suggestions-header')
            sp.add_argument('--markdown')
            sp.add_argument('--data-header')
    dt = sub.add_parser('doctest')
    dt.add_argument('--json')
    dt.add_argument('--root', default=os.getcwd())
    dt.add_argument('files', nargs='*')
    args = ap.parse_args(argv)

    if args.command == 'doctest':
        from . import doctest
        return doctest.main(args)
    started = time.monotonic()
    if args.command in ('extract', 'all'):
        api = ex.extract(args.binding_dir, args.core_dir, args.engine_version)
        ex.write_if_changed(args.json, ex.dumps(api))
    else:
        api = ex.load(args.json)
    if args.command in ('emit', 'all'):
        _emit(api, args)
    print(f'[lua_api] {len(api["classes"])} classes, {len(api["enums"])} enums, {len(api["unresolved"])} unresolved '
          f'({time.monotonic() - started:.1f} s)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
