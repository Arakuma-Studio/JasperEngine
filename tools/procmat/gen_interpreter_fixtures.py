"""Writes editor/tests/procmat/SpirvInterpreterFixtures.h from interpreter_fixtures.glsl.

    tools/build.sh exec linux python3 tools/procmat/gen_interpreter_fixtures.py build/procmat-sweep/procmat-sweep

The editor test has no compiler to call, so it holds glslang's SPIR-V for these shaders.
"""

import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parents[1] / "editor/tests/procmat/SpirvInterpreterFixtures.h"


def main() -> int:
    tool = sys.argv[1]
    shaders = {}
    name = None
    for line in (HERE / "interpreter_fixtures.glsl").read_text(encoding="utf-8").splitlines():
        if line.startswith("//# "):
            name = line[4:].strip()
            shaders[name] = []
        elif name is not None:
            shaders[name].append(line)
    lines = ["// (c) Eduardo Doria and contributors", "// SPDX-License-Identifier: MIT", "",
             "// Generated by tools/procmat/gen_interpreter_fixtures.py from tools/procmat/interpreter_fixtures.glsl.", "",
             "#include <cstdint>", ""]
    with tempfile.TemporaryDirectory() as scratch:
        for name, source in shaders.items():
            frag = Path(scratch) / f"{name}.frag"
            spv = Path(scratch) / f"{name}.spv"
            frag.write_text("\n".join(source) + "\n", encoding="utf-8")
            subprocess.run([tool, "spirv", "--frag", str(frag), "--out", str(spv)], check=True)
            data = spv.read_bytes()
            words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
            lines.append(f"static const uint32_t fixture_{name}[] = {{")
            for i in range(0, len(words), 12):
                lines.append("    " + ", ".join(f"0x{w:08x}u" for w in words[i:i + 12]) + ",")
            lines.append("};")
            lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{OUT}: {len(shaders)} shaders")
    return 0


if __name__ == "__main__":
    sys.exit(main())
