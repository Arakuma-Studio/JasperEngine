"""Writes the reference tables of WaterWavesTest: library/water.glsl's waterWaves (the default,
MatchesReferenceTable) or waterGerstner (--gerstner, GerstnerMatchesReferenceTable) evaluated with
every operation rounded to float32 (as a GPU and the C++ twin do), independently of
engine/core/util/WaterWaves.h.

    python3 tools/gen_water_waves_reference.py > engine/tests/core/util/WaterWavesReference.inl
    python3 tools/gen_water_waves_reference.py --gerstner > engine/tests/core/util/WaterGerstnerReference.inl
"""
import math
import random
import struct
import sys


def f(x):
    return struct.unpack("f", struct.pack("f", x))[0]


def fract(x):
    return f(x - math.floor(x))


def water_waves(xz, time, direction, height, wave_length, speed):
    two_pi = f(6.28318530718)
    length = f(math.sqrt(f(f(direction[0] * direction[0]) + f(direction[1] * direction[1]))))
    d = max(length, f(1e-4))
    first = (f(direction[0] / d), f(direction[1] / d))
    second = (f(f(first[0] * f(0.6428)) - f(first[1] * f(0.7660))), f(f(first[0] * f(0.7660)) + f(first[1] * f(0.6428))))
    length1 = max(f(wave_length), f(1e-3))
    length2 = f(length1 * f(0.6))
    dot1 = f(f(first[0] * xz[0]) + f(first[1] * xz[1]))
    dot2 = f(f(second[0] * xz[0]) + f(second[1] * xz[1]))
    phase1 = f(f(f(dot1 / length1) - fract(f(f(time * speed) / length1))) * two_pi)
    phase2 = f(f(f(f(dot2 / length2) - fract(f(f(time * speed) / length2))) + f(0.37)) * two_pi)
    s1 = f(math.sin(phase1))
    s2 = f(math.sin(phase2))
    return f(height * f(s1 + f(f(0.5) * s2)))


def gerstner_wave(xz, time, d, l, a, c, phase_offset, s, offset):
    two_pi = f(6.28318530718)
    k = f(two_pi / l)
    dot = f(f(d[0] * xz[0]) + f(d[1] * xz[1]))
    phase = f(f(f(f(dot / l) - fract(f(f(time * c) / l))) + phase_offset) * two_pi)
    sin_phase = f(math.sin(phase))
    cos_phase = f(math.cos(phase))
    q = f(f(s * f(0.25)) / k)
    sideways = f(q * cos_phase)
    return (f(offset[0] + f(d[0] * sideways)), f(offset[1] + f(a * sin_phase)), f(offset[2] + f(d[1] * sideways)))


def water_gerstner(xz, time, direction, height, wave_length, speed, steepness):
    length = f(math.sqrt(f(f(direction[0] * direction[0]) + f(direction[1] * direction[1]))))
    scale = max(length, f(1e-4))
    d0 = (f(direction[0] / scale), f(direction[1] / scale))
    d1 = (f(f(d0[0] * f(0.6428)) - f(d0[1] * f(0.7660))), f(f(d0[0] * f(0.7660)) + f(d0[1] * f(0.6428))))
    d2 = (f(f(d0[0] * f(0.8660)) + f(d0[1] * f(0.5))), f(f(d0[1] * f(0.8660)) - f(d0[0] * f(0.5))))
    d3 = (f(f(d0[0] * f(0.1736)) - f(d0[1] * f(0.9848))), f(f(d0[0] * f(0.9848)) + f(d0[1] * f(0.1736))))
    l0 = max(f(wave_length), f(1e-3))
    s = min(max(f(steepness), 0.0), f(0.95))
    offset = (0.0, 0.0, 0.0)
    offset = gerstner_wave(xz, time, d0, l0, height, speed, 0.0, s, offset)
    offset = gerstner_wave(xz, time, d1, f(l0 * f(0.6)), f(height * f(0.5)), f(speed * f(0.7746)), f(0.37), s, offset)
    offset = gerstner_wave(xz, time, d2, f(l0 * f(0.37)), f(height * f(0.28)), f(speed * f(0.6083)), f(0.71), s, offset)
    offset = gerstner_wave(xz, time, d3, f(l0 * f(0.23)), f(height * f(0.16)), f(speed * f(0.4796)), f(0.13), s, offset)
    return offset


def literal(value):
    text = "%.9g" % value
    if "." not in text and "e" not in text and "inf" not in text:
        text += ".0"
    return text + "f"


def main():
    gerstner = "--gerstner" in sys.argv[1:]
    random.seed(23 if gerstner else 22)
    rows = []
    special = [
        ((0.0, 0.0), 0.0, (1.0, 0.3), 0.5, 4.0, 1.5),
        ((3.25, -7.5), 12.5, (0.0, 0.0), 1.0, 2.0, 1.0),      # no direction: the max guard
        ((10.0, 4.0), 7.0, (1.0, 0.0), 0.8, 0.0, 2.0),        # no wave length: the max guard
        ((-250.0, 125.0), 3600.0, (-0.7, 0.7), 1.2, 10.0, 3.0),  # an hour in: fract keeps the phase
        ((1.0, 1.0), 5.0, (0.2, -1.0), 0.0, 6.0, 1.0),        # flat
        ((42.0, -17.0), 0.0, (1.0, 0.3), 2.0, 25.0, 0.0),     # standing
    ]
    for row in special:
        rows.append(row)
    while len(rows) < 64:
        xz = (round(random.uniform(-500, 500), 3), round(random.uniform(-500, 500), 3))
        time = round(random.uniform(0, 1000), 3)
        angle = random.uniform(0, 2 * math.pi)
        scale = random.uniform(0.2, 3)
        direction = (round(math.cos(angle) * scale, 4), round(math.sin(angle) * scale, 4))
        height = round(random.uniform(0, 2), 3)
        length = round(random.uniform(0.5, 50), 3)
        speed = round(random.uniform(0, 10), 3)
        rows.append((xz, time, direction, height, length, speed))
    out = []
    out.append("// (c) Eduardo Doria and contributors")
    out.append("// SPDX-License-Identifier: MIT")
    out.append("")
    if gerstner:
        out.append("// Generated by tools/gen_water_waves_reference.py --gerstner: library/water.glsl's waterGerstner with")
        out.append("// every operation rounded to float32. {x, z, time, direction x, direction y, height, waveLength, speed,")
        out.append("// steepness, offset x, offset y, offset z}")
        for i, (xz, time, direction, height, length, speed) in enumerate(rows):
            steepness = round(random.uniform(0.0, 1.0), 3) if i >= 6 else [0.5, 0.0, 0.95, 1.0, 0.3, 0.7][i]
            o = water_gerstner((f(xz[0]), f(xz[1])), f(time), (f(direction[0]), f(direction[1])), f(height), f(length), f(speed), f(steepness))
            values = [xz[0], xz[1], time, direction[0], direction[1], height, length, speed, steepness]
            out.append("{" + ", ".join(literal(f(v)) for v in values) + ", " + ", ".join(literal(v) for v in o) + "},")
        sys.stdout.write("\n".join(out) + "\n")
        return
    out.append("// Generated by tools/gen_water_waves_reference.py: library/water.glsl's waterWaves with every")
    out.append("// operation rounded to float32. {x, z, time, direction x, direction y, height, waveLength, speed, h}")
    for (xz, time, direction, height, length, speed) in rows:
        h = water_waves((f(xz[0]), f(xz[1])), f(time), (f(direction[0]), f(direction[1])), f(height), f(length), f(speed))
        values = [xz[0], xz[1], time, direction[0], direction[1], height, length, speed]
        out.append("{" + ", ".join(literal(f(v)) for v in values) + ", " + literal(h) + "},")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
