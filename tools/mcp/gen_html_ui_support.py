"""Generate docs/mcp/guide/html-ui-support.md from the engine's HTML/CSS compatibility tables.

    uv run --no-project --with mcp --with pyyaml python tools/mcp/gen_html_ui_support.py
        [--out docs/mcp/guide/html-ui-support.md] [--json-out FILE] [--check]

Runs `jasperengine-editor ui-support` (the editor of harness.editor_command(): JASPER_EDITOR, else
build/linux/editor-install of this checkout or the main one), which prints every row of the
compatibility layer's support tables (engine/core/htmlui/compat/tables) with its support as this
build has it (fork features included) and the diagnostic code registry, and renders them as the
support matrix served as jasper://docs/html-ui-support. --check writes nothing: it exits 1 with a
unified diff when the file differs from what the tables give (the matrix is stale), 0 otherwise.
--json-out also writes the raw JSON.
"""

from __future__ import annotations

import argparse
import difflib
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from harness import REPO, editor_command  # noqa: E402

DEFAULT_OUT = REPO / "docs" / "mcp" / "guide" / "html-ui-support.md"

KINDS = {"element", "attribute", "input_type", "property", "value", "function", "unit", "selector",
         "pseudo_class", "pseudo_element", "at_rule", "media_feature"}
SUPPORTS = ["native", "rewritten", "approximated", "emulated", "fallback", "unsupported", "ignored"]

HEADER = """# HTML/CSS support matrix

Generated by `tools/mcp/gen_html_ui_support.py` from the engine's compatibility tables
(`jasperengine-editor ui-support`). Do not edit by hand. How to build UI:
jasper://docs/html-ui.

Legend: **native**, works as in a browser · **rewritten**, works, the engine translates it ·
**emulated**, works through engine code · **approximated**, works with the limits in Notes ·
**fallback**, approximated until a fork feature lands · **unsupported**, dropped with a
diagnostic; use the replacement · **ignored**, accepted, no effect in a game UI.

A construct that is not native is reported where it is written (`check --ui`, the Console, MCP
`problems`) with the code in the Notes column; the codes are listed at the end.
"""


def ui_support() -> dict:
    cmd = editor_command() + ["ui-support"]
    r = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
    if r.returncode != 0:
        raise SystemExit(f"{' '.join(cmd)} failed (exit {r.returncode}):\n{r.stderr[-2000:]}")
    try:
        data = json.loads(r.stdout)
    except json.JSONDecodeError as e:
        raise SystemExit(f"ui-support printed something that is not JSON ({e}):\n{r.stdout[:2000]}")
    if data.get("version") != 1 or not isinstance(data.get("features"), list):
        raise SystemExit(f"unexpected ui-support output: version {data.get('version')!r}")
    return data


def cell(text) -> str:
    """Markdown table cell: one line, pipes escaped."""
    text = " ".join(str(text or "").split())
    return text.replace("|", "\\|")


def code_cell(text) -> str:
    return f"`{cell(text)}`" if text else ""


def notes(feature: dict) -> str:
    out = cell(feature.get("note", ""))
    code = feature.get("code")
    if code:
        out = f"{out} ({code})" if out else code
    return out


def sort_key(*parts: str):
    return tuple((p.lower(), p) for p in parts)


def table(columns: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(columns) + " |", "|" + "|".join("---" for _ in columns) + "|"]
    for row in rows:
        lines.append("| " + " | ".join(row) + " |")
    return lines


# jasper://docs serves a section above 6 KB as its "### " parts: a big table is cut into
# alphabetical parts of about this size
PART_BYTES = 6000


def initial(name: str) -> str:
    name = name.lstrip("`:@").lower()
    return name[0] if name and name[0].isalpha() else "-"


def parts(title: str, columns: list[str], rows: list[list[str]], names: list[str], other: str = "other") -> list[str]:
    """The table, or (when it is big) the table cut at initial letters into "### <title>: a-c"
    parts; a letter bigger than a part alone is cut by name ("### <title>: border-…-color")."""
    whole = table(columns, rows)
    if sum(len(line) + 1 for line in whole) <= PART_BYTES:
        return whole

    def row_size(row: list[str]) -> int:
        return len("| " + " | ".join(row) + " |") + 1

    groups: list[tuple[str, list[tuple[str, list[str]]]]] = []   # initial -> (name, row), in table order
    for row, name in zip(rows, names):
        key = initial(name)
        if not groups or groups[-1][0] != key:
            groups.append((key, []))
        groups[-1][1].append((name, row))

    out: list[str] = []

    def emit(label: str, items: list[tuple[str, list[str]]]):
        out.extend(["", f"### {title}: {label}", ""])
        out.extend(table(columns, [row for _, row in items]))

    def letters(chunk: list[tuple[str, list]]) -> str:
        first, last = chunk[0][0], chunk[-1][0]
        if first == "-":
            return other
        return first if first == last else f"{first}-{last}"

    def span(items: list[tuple[str, list[str]]]) -> str:
        first, last = cell(items[0][0]), cell(items[-1][0])
        return first if first == last else f"{first} to {last}"

    chunk: list[tuple[str, list]] = []
    size = 0
    for key, items in groups:
        group_size = sum(row_size(row) for _, row in items)
        if chunk and (size + group_size > PART_BYTES or key == "-" or chunk[-1][0] == "-"):
            emit(letters(chunk), [item for _, its in chunk for item in its])
            chunk, size = [], 0
        if group_size > PART_BYTES and key != "-":
            # one letter alone is too big: by name ranges
            piece: list[tuple[str, list[str]]] = []
            piece_size = 0
            for item in items:
                if piece and piece_size + row_size(item[1]) > PART_BYTES:
                    emit(span(piece), piece)
                    piece, piece_size = [], 0
                piece.append(item)
                piece_size += row_size(item[1])
            emit(span(piece), piece)
            continue
        chunk.append((key, items))
        size += group_size
    if chunk:
        emit(letters(chunk), [item for _, its in chunk for item in its])
    return out[1:]


def render(data: dict) -> str:
    by_kind: dict[str, list[dict]] = {k: [] for k in KINDS}
    for feature in data["features"]:
        kind = feature.get("kind")
        if kind not in by_kind:
            raise SystemExit(f"unknown feature kind {kind!r}: {feature}")
        if feature.get("support") not in SUPPORTS:
            raise SystemExit(f"unknown support {feature.get('support')!r}: {feature}")
        by_kind[kind].append(feature)

    def rows(kind: str, first, extra=None) -> list[list[str]]:
        items = sorted(by_kind[kind], key=lambda f: sort_key(*first(f)))
        out = []
        for f in items:
            row = [code_cell(x) for x in first(f)]
            if extra:
                row += extra(f)
            row += [cell(f["support"]), notes(f), cell(f.get("suggestion", ""))]
            out.append(row)
        return out

    def names(kind: str, first) -> list[str]:
        return [first(f)[0] for f in sorted(by_kind[kind], key=lambda f: sort_key(*first(f)))]

    lines = [HEADER.rstrip("\n"), ""]

    name_key = lambda f: [f["name"]]   # noqa: E731
    lines += ["## Elements", ""]
    lines += parts("Elements", ["Element", "Support", "Notes", "Instead"], rows("element", name_key), names("element", name_key))
    lines += ["", "### Input types", ""]
    lines += table(["`<input type>`", "Support", "Notes", "Instead"], rows("input_type", lambda f: [f["name"]]))

    lines += ["", "## Attributes", "", "`*` = every element; `data-*`, `aria-*` and `on*` are patterns.", ""]
    attribute_key = lambda f: [f["name"], f.get("element", "*")]   # noqa: E731
    lines += parts("Attributes", ["Attribute", "Element", "Support", "Notes", "Instead"],
                   rows("attribute", attribute_key), names("attribute", attribute_key))

    lines += ["", "## CSS properties", ""]
    property_key = lambda f: [f["name"]]   # noqa: E731
    lines += parts("Properties", ["Property", "Support", "Notes", "Instead"], rows("property", property_key),
                   names("property", property_key), other="vendor-prefixed and custom")

    lines += ["", "## Values, functions and units", "",
              "Values of a property that are not handled like the property's other values; `<...>` names a value type.", ""]
    value_key = lambda f: [f.get("property", ""), f["name"]]   # noqa: E731
    lines += parts("Values", ["Property", "Value", "Support", "Notes", "Instead"], rows("value", value_key),
                   names("value", value_key), other="vendor-prefixed and custom properties")
    function_key = lambda f: [f["name"] + "()"]   # noqa: E731
    function_rows = parts("Functions", ["Function", "Support", "Notes", "Instead"], rows("function", function_key),
                          names("function", function_key))
    lines += ([""] if function_rows[0].startswith("### ") else ["", "### Functions", ""]) + function_rows
    lines += ["", "### Units", ""]
    lines += table(["Unit", "Support", "Notes", "Instead"], rows("unit", name_key))

    lines += ["", "## Selectors, pseudo-classes and pseudo-elements"]
    for kind, title, column in (("selector", "Selectors and combinators", "Selector"),
                                ("pseudo_class", "Pseudo-classes", "Pseudo-class"),
                                ("pseudo_element", "Pseudo-elements", "Pseudo-element")):
        # by name, the leading colons aside
        key = lambda f: [f["name"].lstrip(":"), f["name"]]   # noqa: E731
        items = sorted(by_kind[kind], key=lambda f: sort_key(*key(f)))
        kind_rows = [[code_cell(f["name"]), cell(f["support"]), notes(f), cell(f.get("suggestion", ""))] for f in items]
        part = parts(title, [column, "Support", "Notes", "Instead"], kind_rows, [f["name"] for f in items])
        lines += ([""] if part[0].startswith("### ") else ["", f"### {title}", ""]) + part
    lines += ["", "## At-rules", ""]
    lines += table(["At-rule", "Support", "Notes", "Instead"], rows("at_rule", lambda f: [f["name"]]))
    lines += ["", "### Media features and types", ""]
    lines += table(["Feature", "Support", "Notes", "Instead"], rows("media_feature", lambda f: [f["name"]]))

    lines += ["", "## Diagnostic codes", "",
              "Severity \"by case\": the construct decides (the default is given).", ""]
    diag_rows = []
    for d in sorted(data.get("diagnostics", []), key=lambda d: d["code"]):
        severity = d.get("severity", "")
        if d.get("by_case"):
            severity = f"by case ({severity})"
        meaning = f"**{cell(d.get('summary', ''))}** (`{cell(d.get('name', ''))}`)"
        if d.get("help"):
            meaning += ": " + cell(d["help"])
        diag_rows.append([code_cell(d["code"]), cell(severity), meaning])
    # one part per area (GEN, HTML, CSS, ...)
    areas: dict[str, list[list[str]]] = {}
    for d, row in zip(sorted(data.get("diagnostics", []), key=lambda d: d["code"]), diag_rows):
        areas.setdefault(d["code"].split("-")[1], []).append(row)
    for area, area_rows in areas.items():
        lines += [f"### {area}", ""] + table(["Code", "Severity", "Meaning"], area_rows) + [""]
    lines.pop()
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=str(DEFAULT_OUT), help="Markdown file (default: %(default)s)")
    ap.add_argument("--json-out", help="also write the ui-support JSON here")
    ap.add_argument("--check", action="store_true", help="exit 1 with a diff when --out is stale; write nothing")
    args = ap.parse_args()

    data = ui_support()
    text = render(data)
    out = Path(args.out)
    if args.json_out:
        Path(args.json_out).write_text(json.dumps(data, indent=1) + "\n")
    if args.check:
        current = out.read_text() if out.exists() else ""
        if current == text:
            print(f"{out}: current ({len(data['features'])} features, {len(data.get('diagnostics', []))} codes)")
            return 0
        diff = difflib.unified_diff(current.splitlines(keepends=True), text.splitlines(keepends=True),
                                    fromfile=f"{out} (committed)", tofile=f"{out} (from ui-support)")
        sys.stdout.writelines(diff)
        print(f"\n{out} is stale: run tools/mcp/gen_html_ui_support.py", file=sys.stderr)
        return 1
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(f"wrote {out} ({len(data['features'])} features, {len(data.get('diagnostics', []))} codes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
