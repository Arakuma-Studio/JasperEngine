GENERATED_HEADER = "// This file is auto-generated by JasperEngine Editor"


def fail(message: str) -> None:
    raise harness.TestFailure(message)


def check(cond, message: str) -> None:
    if not cond:
        fail(message)


def first_difference(actual: str, expected: str) -> str:
    a = actual.splitlines()
    b = expected.splitlines()
    for i in range(max(len(a), len(b))):
        la = a[i] if i < len(a) else "<end>"
        lb = b[i] if i < len(b) else "<end>"
        if la != lb:
            return f"line {i + 1}:\n  now:    {la}\n  golden: {lb}"
    return "(same lines, different bytes)"


def normalized_scene(text: str) -> str:
    """The scene text with its shaderKeys entries sorted: the set is ordered by keys holding
    custom shader ids, which each editor session hands out in its own order"""
    lines = text.splitlines(keepends=True)
    out: list[str] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        out.append(line)
        i += 1
        if not line.startswith("shaderKeys:"):
            continue
        entries: list[str] = []
        current = ""
        while i < len(lines) and (lines[i].startswith(" ") or lines[i].startswith("-")):
            if lines[i].startswith("-") and current:
                entries.append(current)
                current = ""
            current += lines[i]
            i += 1
        if current:
            entries.append(current)
        out.extend(sorted(entries))
    return "".join(out)


def normalized_source(text: str, project: Path) -> str:
    return text.replace(str(project), "<project>").replace(project.as_posix(), "<project>")


def compare_or_update(path: Path, actual: str, what: str, mismatches: list[str]) -> None:
    if UPDATE:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(actual, encoding="utf-8", newline="")
        return
    if not path.exists():
        mismatches.append(f"{what}: no golden {path.relative_to(harness.REPO)}")
        return
    expected = path.read_text(encoding="utf-8")
    if expected != actual:
        mismatches.append(f"{what} differs from {path.relative_to(harness.REPO)}: {first_difference(actual, expected)}")


def fixture_projects() -> list[Path]:
    projects = sorted(p.parent for p in FIXTURES.glob("*/project.yaml"))
    parity = PARITY / "project.yaml"
    if parity.exists() and PARITY not in projects:
        projects.append(PARITY)
    return projects


def generated_sources(project: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    generated = project / ".jasperengine" / "generated"
    if not generated.is_dir():
        return out
    for path in sorted(generated.glob("*.cpp")):
        text = path.read_text(encoding="utf-8", errors="replace")
        if text.startswith(GENERATED_HEADER):
            out[path.name] = normalized_source(text, project)
    return out


async def resave(ed: Editor, project: Path, name: str, mismatches: list[str], sources: dict[str, str]) -> None:
    """Opens and saves every scene and prefab of the editor's project, then the project; compares
    what it wrote (and the scene sources it generated) with the goldens of `name`"""
    scenes = sorted(p.relative_to(project).as_posix() for p in project.rglob("*.scene")
                    if ".jasperengine" not in p.parts)
    for rel in scenes:
        opened = await ed.call("open_scene", scene=rel, close_previous=True)
        scene_id = opened["scene"]["id"] if isinstance(opened.get("scene"), dict) else opened.get("scene_id")
        await ed.call("save_scene", scene=scene_id if scene_id is not None else rel, allow_data_loss=True)
        text = (project / rel).read_text(encoding="utf-8")
        compare_or_update(GOLDEN / name / (rel + ".golden"), normalized_scene(text), f"{name}/{rel}", mismatches)
    prefabs = sorted(p.relative_to(project).as_posix() for p in project.rglob("*.prefab")
                     if ".jasperengine" not in p.parts)
    for rel in prefabs:
        await ed.call("prefab_mode", action="open", prefab=rel)
        await ed.call("prefab_mode", action="save", allow_data_loss=True)
        await ed.call("prefab_mode", action="close", unsaved="discard")
        text = (project / rel).read_text(encoding="utf-8")
        compare_or_update(GOLDEN / name / (rel + ".golden"), text, f"{name}/{rel}", mismatches)
    await ed.call("save_project")
    compare_or_update(GOLDEN / name / "project.yaml.golden", (project / "project.yaml").read_text(encoding="utf-8"),
                      f"{name}/project.yaml", mismatches)
    for file, text in generated_sources(project).items():
        sources[f"{name}/{file}"] = text


def prefab_projects(root: Path) -> list[tuple[str, Path]]:
    """The projects tools/prefab-fixtures.py writes from the TappyPlane fixture (none without it)"""
    fixture = os.environ.get("JASPER_FIXTURE") or os.environ.get("FIXTURE")
    if not fixture or not Path(fixture).is_dir():
        return []
    made = []
    for kind in ("legacy", "nested", "variant"):
        out = root / f"prefab-{kind}"
        run = subprocess.run([sys.executable, str(harness.REPO / "tools" / "prefab-fixtures.py"), kind, str(out)],
                             env=dict(os.environ, FIXTURE=fixture), capture_output=True, text=True, timeout=300)
        check(run.returncode == 0, f"prefab-fixtures.py {kind}: {run.stderr[-2000:]}")
        made.append((f"prefab-{kind}", out))
    return made


SOURCES: dict[str, str] = {}


async def test_golden_resave():
    mismatches: list[str] = []
    SOURCES.clear()
    for project in fixture_projects():
        name = project.name
        async with Editor(project=project) as ed:
            await resave(ed, ed.project, name, mismatches, SOURCES)
    root = Path(tempfile.mkdtemp(prefix="jasper-reflection-prefabs-"))
    try:
        for name, project in prefab_projects(root):
            async with Editor(project=project) as ed:
                await resave(ed, ed.project, name, mismatches, SOURCES)
    finally:
        shutil.rmtree(root, ignore_errors=True)
    check(not mismatches, "re-saved files differ from the goldens:\n" + "\n".join(mismatches[:20]))


async def test_codegen_golden():
    check(SOURCES, "test_golden_resave generated no scene sources")
    mismatches: list[str] = []
    for key, text in sorted(SOURCES.items()):
        compare_or_update(GOLDEN / "codegen" / (key + ".golden"), text, f"generated {key}", mismatches)
    check(not mismatches, "generated C++ differs from the goldens:\n" + "\n".join(mismatches[:20]))


