def layout_rows(layout: dict, entity: int | None = None) -> list[dict]:
    """The visible rows, without what only reflects the values drawn"""
    return [{k: row[k] for k in ("component", "path", "label", "kind", "group", "read_only")}
            for row in layout["rows"] if row.get("visible", True)]


async def test_inspector_layout_parity(ed: Editor):
    await ed.call("focus_window", window="inspector")
    scenes: dict[str, int] = {}
    captured: dict[str, list[dict]] = {}
    problems: list[str] = []
    for case, scene_type, entity_type, states in LAYOUT_CASES:
        if scene_type not in scenes:
            made = await ed.call("create_scene", name=f"Layout{scene_type}", type=scene_type, path=f"scenes/Layout{scene_type}")
            scenes[scene_type] = made["scene"]["id"]
        scene = scenes[scene_type]
        await ed.call("select_scene", scene=scene)
        made = await ed.call_raw("create_entity", {"scene": scene, "type": entity_type, "name": case})
        if made.is_error:
            problems.append(f"{case}: create_entity {entity_type}: {made.text[:200]}")
            continue
        entity = made.value()["entity_id"]
        await ed.call("select_entities", scene=scene, entities=[entity])
        for index, values in enumerate(states):
            if values:
                await ed.call("set_properties", scene=scene, entity=entity, values=values)
            layout = await ed.call("get_inspector_layout", scene=scene, entities=[entity])
            captured[f"{case}#{index}"] = layout_rows(layout)
    check(not problems, "\n".join(problems))
    golden = GOLDEN / "inspector_layouts.json"
    if UPDATE:
        golden.parent.mkdir(parents=True, exist_ok=True)
        golden.write_text(json.dumps(captured, indent=1, sort_keys=True) + "\n", encoding="utf-8")
        return
    check(golden.exists(), f"no golden {golden}")
    expected = json.loads(golden.read_text(encoding="utf-8"))
    differences = []
    for key in sorted(set(expected) | set(captured)):
        if expected.get(key) != captured.get(key):
            want = expected.get(key) or []
            got = captured.get(key) or []
            first = next((i for i in range(max(len(want), len(got)))
                          if (want[i] if i < len(want) else None) != (got[i] if i < len(got) else None)), None)
            differences.append(f"{key}: row {first}: now {got[first] if first is not None and first < len(got) else None}, "
                               f"golden {want[first] if first is not None and first < len(want) else None}")
    check(not differences, "Inspector layouts differ from the hand drawers':\n" + "\n".join(differences[:30]))
