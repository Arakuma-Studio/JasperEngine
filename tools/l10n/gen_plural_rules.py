"""Generate the CLDR plural rules and number symbols of the game localisation runtime
(docs/specs/game-ui-localization.md R4, D4).

Reads a pinned CLDR JSON release from npm (cldr-core: supplemental/plurals.json; cldr-numbers-full:
each locale's latn symbols, percent pattern and grouping), checked against the registry's sha512,
and writes:

- engine/core/localization/PluralRules.gen.inc: one function per distinct cardinal rule set (a chain
  of conditions over the operands n, i, v, w, f, t, e), the sorted language -> rule table, and the
  number symbols of every locale that differs from its truncated parent;
- engine/core/localization/LICENSE.cldr.txt: the release's licence notice;
- engine/tests/core/localization/PluralSamples.gen.inc: every @integer / @decimal sample of every
  language with its category (PluralRulesTest.GeneratedTableMatchesCldrSamples).

    python3 tools/l10n/gen_plural_rules.py [--cache DIR]     # writes the files
    python3 tools/l10n/gen_plural_rules.py --check           # fails when a committed file differs

The tarballs are cached in --cache (default: ~/.cache/jasperengine/cldr). Updating CLDR is a new
pin below plus a run and AC2.
"""

import argparse
import base64
import hashlib
import io
import json
import os
import re
import sys
import tarfile
import urllib.request
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
OUT_RULES = ROOT / "engine/core/localization/PluralRules.gen.inc"
OUT_LICENSE = ROOT / "engine/core/localization/LICENSE.cldr.txt"
OUT_SAMPLES = ROOT / "engine/tests/core/localization/PluralSamples.gen.inc"

CLDR_VERSION = "49.0.0"
PACKAGES = {
    "cldr-core": "sha512-2Z2dYeDO95AbKIG9dIUdZy6DD4f0hhHjTYnaHZj/9JTQ82pX5EsJlCs2BXPWi4vd1d98MwotOivh4Uthxwri4A==",
    "cldr-numbers-full": "sha512-8Ww1u18Sbl7h8UA1tJ7pKFuzV4wKLYHk20wRJE8wewNKS0Ex83DoYawoIrLfzTGWjUt41rjrBRJv9TC3THiznA==",
}
CATEGORIES = ["zero", "one", "two", "few", "many", "other"]
HEADER = ("// Generated by tools/l10n/gen_plural_rules.py from CLDR " + CLDR_VERSION +
          " (Unicode License v3, LICENSE.cldr.txt) - DO NOT EDIT\n")


def fetch(name, cache):
    integrity = PACKAGES[name]
    path = Path(cache) / f"{name}-{CLDR_VERSION}.tgz"
    if not path.exists():
        url = f"https://registry.npmjs.org/{name}/-/{name}-{CLDR_VERSION}.tgz"
        path.parent.mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(url, timeout=120) as response:
            data = response.read()
        path.write_bytes(data)
    data = path.read_bytes()
    digest = "sha512-" + base64.b64encode(hashlib.sha512(data).digest()).decode()
    if digest != integrity:
        raise SystemExit(f"{path}: sha512 differs from the pinned {name} {CLDR_VERSION}; delete it and run again")
    return tarfile.open(fileobj=io.BytesIO(data))


# ---- plural rule conditions -> C++

TOKEN = re.compile(r"\s*(?:(and|or)\b|([nivwftec])\b|(%)|(!=|=)|(\d+(?:\.\d+)?)|(\.\.)|(,))")


def compile_condition(text):
    """`v = 0 and i % 10 = 1 or ...` -> a C++ boolean expression over `o` (PluralOperands)."""
    tokens = []
    pos = 0
    text = text.strip()
    while pos < len(text):
        m = TOKEN.match(text, pos)
        if not m or m.end() == pos:
            raise SystemExit(f"cannot read plural condition: {text!r} at {pos}")
        tokens.append(next((i, g) for i, g in enumerate(m.groups()) if g is not None))
        pos = m.end()
    ors = []
    ands = []
    i = 0
    while i < len(tokens):
        kind, value = tokens[i]
        if kind == 0:
            if value == "or":
                ors.append(ands)
                ands = []
            i += 1
            continue
        if kind != 1:
            raise SystemExit(f"unexpected token {value!r} in {text!r}")
        operand = "e" if value == "c" else value
        i += 1
        modulus = None
        if i < len(tokens) and tokens[i][0] == 2:
            modulus = tokens[i + 1][1]
            i += 2
        op = tokens[i][1]
        i += 1
        ranges = []
        while i < len(tokens) and tokens[i][0] == 4:
            low = tokens[i][1]
            high = low
            i += 1
            if i < len(tokens) and tokens[i][0] == 5:
                high = tokens[i + 1][1]
                i += 2
            ranges.append((low, high))
            if i < len(tokens) and tokens[i][0] == 6:
                i += 1
            else:
                break
        ands.append(relation(operand, modulus, op, ranges))
    ors.append(ands)
    return " || ".join("(" + " && ".join(a) + ")" for a in ors)


def relation(operand, modulus, op, ranges):
    if operand == "n":
        value = f"std::fmod(o.n, {modulus}.0)" if modulus else "o.n"
        tests = []
        for low, high in ranges:
            if low == high:
                tests.append(f"{value} == {low}.0")
            else:
                tests.append(f"(isWhole({value}) && {value} >= {low}.0 && {value} <= {high}.0)")
    else:
        value = f"(o.{operand} % {modulus})" if modulus else f"o.{operand}"
        tests = []
        for low, high in ranges:
            tests.append(f"{value} == {low}" if low == high else f"({value} >= {low} && {value} <= {high})")
    test = " || ".join(tests)
    return f"({test})" if op == "=" else f"!({test})"


def parse_rules(rules):
    """{category: (condition, integer samples, decimal samples)} of one language."""
    out = {}
    for key, text in rules.items():
        category = key.replace("pluralRule-count-", "")
        condition, _, samples = text.partition("@")
        samples = "@" + samples if samples else ""
        integers = re.search(r"@integer([^@]*)", samples)
        decimals = re.search(r"@decimal([^@]*)", samples)
        out[category] = (condition.strip(), expand(integers.group(1)) if integers else [],
                         expand(decimals.group(1)) if decimals else [])
    return out


def expand(text):
    values = []
    for part in text.split(","):
        part = part.strip()
        if not part or part == "…":
            continue
        if "~" in part:
            low, high = part.split("~")
            if "c" in low or "e" in low:
                values += [low, high]
                continue
            places = len(low.split(".")[1]) if "." in low else 0
            step = Decimal(1).scaleb(-places)
            value = Decimal(low)
            # a long range keeps its first 15 values and its end
            expanded = []
            while value <= Decimal(high):
                expanded.append(f"{value:.{places}f}")
                value += step
            values += expanded if len(expanded) <= 16 else expanded[:15] + expanded[-1:]
        else:
            values.append(part)
    return values


def rule_function(rules):
    lines = []
    for category in CATEGORIES:
        if category == "other" or category not in rules:
            continue
        condition = rules[category][0]
        if condition:
            lines.append(f"        if ({compile_condition(condition)}) return PluralCategory::{category.capitalize()};")
    lines.append("        return PluralCategory::Other;")
    return "\n".join(lines)


# ---- number symbols

def number_row(numbers):
    symbols = numbers.get("symbols-numberSystem-latn", {})
    decimal_pattern = numbers.get("decimalFormats-numberSystem-latn", {}).get("standard", "#,##0.###")
    percent = numbers.get("percentFormats-numberSystem-latn", {}).get("standard", "#,##0%").split(";")[0]
    integer_part = decimal_pattern.split(".")[0]
    groups = integer_part.split(",")
    primary = len(groups[-1]) if len(groups) > 1 else 0
    secondary = len(groups[-2]) if len(groups) > 2 else primary
    percent_sign = symbols.get("percentSign", "%")
    prefix = percent.startswith("%")
    digits = [m.start() for m in re.finditer(r"[#0]", percent)]
    spacer = percent[1:digits[0]] if prefix else percent[digits[-1] + 1:percent.index("%")]
    return (symbols.get("decimal", "."), symbols.get("group", ","), symbols.get("minusSign", "-"), percent_sign,
            1 if prefix else 0, spacer, primary, secondary, int(numbers.get("minimumGroupingDigits", "1")))


def c_string(text):
    """A C string literal; bytes outside printable ASCII as octal escapes (never run on)."""
    out = ""
    for byte in text.encode("utf-8"):
        out += f"\\{byte:03o}" if byte < 0x20 or byte >= 0x7f or byte in (0x22, 0x5c) else chr(byte)
    return '"' + out + '"'


def generate(cache):
    core = fetch("cldr-core", cache)
    plurals = json.load(core.extractfile("package/supplemental/plurals.json"))["supplemental"]["plurals-type-cardinal"]
    licence = core.extractfile("package/LICENSE").read().decode("utf-8")

    # distinct rule sets
    bodies = {}
    languages = []
    samples = []
    for tag in sorted(plurals):
        rules = parse_rules(plurals[tag])
        body = rule_function(rules)
        index = bodies.setdefault(body, len(bodies))
        languages.append((tag, index))
        for category in CATEGORIES:
            if category in rules:
                for value in rules[category][1] + rules[category][2]:
                    samples.append((tag, value, category))

    numbers = fetch("cldr-numbers-full", cache)
    rows = {}
    for name in numbers.getnames():
        if not name.endswith("/numbers.json"):
            continue
        data = json.load(numbers.extractfile(name))["main"]
        tag = list(data)[0]
        rows[tag] = number_row(data[tag]["numbers"])
    root = rows.get("und") or rows.get("root") or (".", ",", "-", "%", 0, "", 3, 3, 1)

    def parent_row(tag):
        parts = tag.split("-")
        while len(parts) > 1:
            parts.pop()
            if "-".join(parts) in rows:
                return rows["-".join(parts)]
        return root

    symbol_rows = [(tag, row) for tag, row in sorted(rows.items()) if tag not in ("und", "root") and row != parent_row(tag)]

    out = [HEADER, "// Included once by engine/core/localization/PluralRules.cpp.", ""]
    out.append("namespace {")
    out.append("")
    out.append("    inline bool isWhole(double value) { return value == std::floor(value); }")
    out.append("")
    out.append("    PluralCategory selectRule(int rule, const PluralOperands& o) {")
    out.append("        switch (rule) {")
    for body, index in sorted(bodies.items(), key=lambda item: item[1]):
        out.append(f"        case {index}: {{")
        out.append("\n".join("    " + line for line in body.split("\n")))
        out.append("        }")
    out.append("        default: return PluralCategory::Other;")
    out.append("        }")
    out.append("    }")
    out.append("")
    out.append("    struct PluralLanguageRow { const char* tag; uint8_t rule; };")
    out.append("    // sorted by tag (strcmp)")
    out.append("    constexpr PluralLanguageRow kPluralLanguages[] = {")
    languages.sort(key=lambda item: item[0].encode())
    for tag, index in languages:
        out.append(f"        {{\"{tag}\", {index}}},")
    out.append("    };")
    out.append(f"    constexpr int kRootRule = {dict(languages)['und']};")
    out.append("")
    out.append("    struct NumberSymbolsRow { const char* tag; NumberSymbols symbols; };")
    out.append("    // locales whose symbols differ from their truncated parent's, sorted by tag (strcmp)")
    out.append(f"    constexpr NumberSymbols kRootSymbols = {symbols_literal(root)};")
    out.append("    constexpr NumberSymbolsRow kNumberSymbols[] = {")
    symbol_rows.sort(key=lambda item: item[0].encode())
    for tag, row in symbol_rows:
        out.append(f"        {{\"{tag}\", {symbols_literal(row)}}},")
    out.append("    };")
    out.append("")
    out.append("}")
    rules_text = "\n".join(out) + "\n"

    sample_lines = [HEADER, "// {language, sample, category} for PluralRulesTest", "static const PluralSample kPluralSamples[] = {"]
    for tag, value, category in samples:
        sample_lines.append(f"    {{\"{tag}\", \"{value}\", PluralCategory::{category.capitalize()}}},")
    sample_lines.append("};")
    samples_text = "\n".join(sample_lines) + "\n"
    licence_text = (f"The plural rules and number symbols in PluralRules.gen.inc are generated from the Unicode CLDR\n"
                    f"{CLDR_VERSION} JSON release (npm cldr-core, cldr-numbers-full) by tools/l10n/gen_plural_rules.py.\n\n"
                    + licence)
    return {OUT_RULES: rules_text, OUT_SAMPLES: samples_text, OUT_LICENSE: licence_text}


def symbols_literal(row):
    decimal, group, minus, percent, prefix, spacer, primary, secondary, minimum = row
    return (f"{{{c_string(decimal)}, {c_string(group)}, {c_string(minus)}, {c_string(percent)}, {c_string(spacer)}, "
            f"{prefix}, {primary}, {secondary}, {minimum}}}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--cache", default=os.path.join(os.path.expanduser("~"), ".cache", "jasperengine", "cldr"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files = generate(args.cache)
    stale = []
    for path, text in files.items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old == text:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("stale: " + ", ".join(stale) + " (run tools/l10n/gen_plural_rules.py)")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
