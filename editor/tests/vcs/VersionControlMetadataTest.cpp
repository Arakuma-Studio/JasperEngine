namespace {
    size_t vcsMetadataOccurrences(const std::string& text, const std::string& what) {
        size_t count = 0;
        for (size_t at = text.find(what); at != std::string::npos; at = text.find(what, at + what.size())) count++;
        return count;
    }
}

// Lines a user adds to the generated files survive the refreshes: the project's save and a Git
// LFS / Lockable Scenes change rewrite only the editor's own block
TEST(VersionControlMetadata, UserLinesSurviveRefreshes) {
    VcsSandbox box;
    const fs::path dir = box.path("UserLines");
    {
        Project project;
        project.setSkipProjectLock(true);
        std::string error;
        ASSERT_TRUE(project.createProjectAt(dir, "UserLines", &error)) << error;
        ASSERT_TRUE(project.saveProject());
        release(project);
    }
    writeFile(dir / ".gitignore", readFile(dir / ".gitignore") + "\n# local secrets\nsecrets.env\n");
    writeFile(dir / ".gitattributes", readFile(dir / ".gitattributes") + "docs/** linguist-documentation\n");
    {
        Project project;
        project.setSkipProjectLock(true);
        ASSERT_TRUE(project.loadProject(dir, false));
        ASSERT_TRUE(project.saveProject());
        VcsProjectSettings settings = project.getVcsProjectSettings();
        settings.lfs = false;
        project.setVcsProjectSettings(settings);
        ASSERT_TRUE(project.saveProject());
        release(project);
    }
    const std::string ignore = readFile(dir / ".gitignore");
    const std::string attributes = readFile(dir / ".gitattributes");
    EXPECT_EQ(vcsMetadataOccurrences(ignore, "secrets.env\n"), 1u) << ignore;
    EXPECT_EQ(vcsMetadataOccurrences(attributes, "docs/** linguist-documentation\n"), 1u) << attributes;
    // the block follows the settings: no LFS line of the previous variant is left
    EXPECT_EQ(attributes.find("filter=lfs"), std::string::npos) << attributes;
    EXPECT_NE(attributes.find("*.png     binary"), std::string::npos) << attributes;

    box.gitOk(dir, {"init", "-q"});
    writeFile(dir / "docs" / "a.md", "doc\n");
    writeFile(dir / "secrets.env", "x\n");
    EXPECT_NE(box.gitOk(dir, {"check-ignore", "secrets.env"}).find("secrets.env"), std::string::npos);
    EXPECT_EQ(attributeOf(box, dir, "docs/a.md", "linguist-documentation"), "set");
}

// A file an older editor wrote (the marker, no end marker): its own lines are kept once, the
// lines any editor generated are not (another LFS variant's, an earlier template's)
TEST(VersionControlMetadata, OlderEditorsFileKeepsOnlyTheUsersLines) {
    VcsSandbox box;
    const fs::path dir = box.path("prefab-runtime");
    fs::copy(fs::path(JASPER_TEST_REPO_DIR) / "tools/fixtures/prefab-runtime", dir, fs::copy_options::recursive);
    writeFile(dir / ".gitattributes",
              "# Generated by JasperEngine Editor.\r\n\r\n* text=auto eol=lf\r\n\r\n*.scene   text eol=lf\r\n"
              "*.png     filter=lfs diff=lfs merge=lfs -text lockable\r\n*.psd     filter=lfs diff=lfs merge=lfs -text lockable\r\n"
              "*.blend binary\r\n\r\n*.wav     binary\r\n");
    {
        Project project;
        project.setSkipProjectLock(true);
        ASSERT_TRUE(project.loadProject(dir, false));
        EXPECT_FALSE(project.getVcsProjectSettings().lfs);
        ASSERT_TRUE(project.saveProject());
        release(project);
    }
    const std::string attributes = readFile(dir / ".gitattributes");
    EXPECT_EQ(attributes.find("filter=lfs"), std::string::npos) << attributes;
    EXPECT_EQ(attributes.find("*.psd"), std::string::npos) << attributes;
    EXPECT_EQ(vcsMetadataOccurrences(attributes, "*.blend binary"), 1u) << attributes;
    EXPECT_GT(attributes.find("*.blend binary"), attributes.find("End of the JasperEngine Editor's lines")) << attributes;
}
