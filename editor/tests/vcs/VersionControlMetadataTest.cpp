namespace {

    std::string attributeOf(const VcsSandbox& box, const fs::path& repo, const std::string& path, const std::string& attribute) {
        // "path: attribute: value"
        const std::string out = box.gitOk(repo, {"check-attr", attribute, "--", path});
        const size_t colon = out.rfind(": ");
        return colon == std::string::npos ? std::string() : out.substr(colon + 2, out.find('\n', colon) - colon - 2);
    }

    void release(Project& project) {
        for (SceneProject& scene : project.getScenes()) CommandHandle::remove(scene.id);
        project.releaseScenes();
    }

}

TEST(VersionControlMetadata, NewProjectGetsLfsAndLockable) {
    VcsSandbox box;
    const fs::path dir = box.path("NewGame");
    {
        Project project;
        project.setSkipProjectLock(true);
        std::string error;
        ASSERT_TRUE(project.createProjectAt(dir, "NewGame", &error)) << error;
        EXPECT_TRUE(project.getVcsProjectSettings().lfs);
        ASSERT_TRUE(project.saveProject());
        release(project);
    }
    const std::string attributes = readFile(dir / ".gitattributes");
    EXPECT_NE(attributes.find("filter=lfs diff=lfs merge=lfs -text lockable"), std::string::npos) << attributes;
    EXPECT_NE(attributes.find("*.psd"), std::string::npos);
    EXPECT_NE(attributes.find("*.meta"), std::string::npos);
    EXPECT_NE(attributes.find("merge=jasperengine-scene"), std::string::npos);
    EXPECT_NE(readFile(dir / ".gitignore").find("*.orig"), std::string::npos);
    EXPECT_NE(readFile(dir / "project.yaml").find("lfs: true"), std::string::npos);

    // git agrees: LFS for the binaries, never for scenes or metas
    box.gitOk(dir, {"init", "-q"});
    EXPECT_EQ(attributeOf(box, dir, "art/hero.png", "filter"), "lfs");
    EXPECT_EQ(attributeOf(box, dir, "art/hero.png", "lockable"), "set");
    EXPECT_EQ(attributeOf(box, dir, "Main.scene", "filter"), "unspecified");
    EXPECT_EQ(attributeOf(box, dir, "art/hero.png.meta", "filter"), "unspecified");
    EXPECT_EQ(attributeOf(box, dir, "Main.scene", "merge"), "jasperengine-scene");
    EXPECT_EQ(attributeOf(box, dir, "Main.scene", "lockable"), "unspecified");
}

TEST(VersionControlMetadata, ExistingProjectKeepsBinariesOutOfLfs) {
    VcsSandbox box;
    const fs::path dir = box.path("prefab-runtime");
    fs::copy(fs::path(JASPER_TEST_REPO_DIR) / "tools/fixtures/prefab-runtime", dir, fs::copy_options::recursive);
    // the generated files, as an older editor left them
    writeFile(dir / ".gitattributes", "# Generated by JasperEngine Editor.\n\n*.png binary\n");
    {
        Project project;
        project.setSkipProjectLock(true);
        ASSERT_TRUE(project.loadProject(dir, false));
        EXPECT_FALSE(project.getVcsProjectSettings().lfs);
        ASSERT_TRUE(project.saveProject());
        release(project);
    }
    const std::string attributes = readFile(dir / ".gitattributes");
    EXPECT_EQ(attributes.find("filter=lfs"), std::string::npos) << attributes;
    EXPECT_EQ(attributes.find("lockable"), std::string::npos) << attributes;
    EXPECT_NE(attributes.find("*.png     binary"), std::string::npos) << attributes;
    EXPECT_NE(attributes.find("*.meta"), std::string::npos);
    EXPECT_NE(attributes.find("merge=jasperengine-scene"), std::string::npos);
    EXPECT_EQ(readFile(dir / "project.yaml").find("versionControl:"), std::string::npos);

    // lockable scenes, on request
    {
        Project project;
        project.setSkipProjectLock(true);
        ASSERT_TRUE(project.loadProject(dir, false));
        VcsProjectSettings settings = project.getVcsProjectSettings();
        settings.lockScenes = true;
        project.setVcsProjectSettings(settings);
        release(project);
    }
    EXPECT_NE(readFile(dir / ".gitattributes").find("merge=jasperengine-scene lockable"), std::string::npos);
}

TEST(VersionControlMetadata, UserAuthoredFileIsUntouched) {
    VcsSandbox box;
    const fs::path dir = box.path("prefab-runtime");
    fs::copy(fs::path(JASPER_TEST_REPO_DIR) / "tools/fixtures/prefab-runtime", dir, fs::copy_options::recursive);
    const std::string mine = "# my own rules\n*.png filter=lfs diff=lfs merge=lfs -text\n";
    writeFile(dir / ".gitattributes", mine);
    {
        Project project;
        project.setSkipProjectLock(true);
        ASSERT_TRUE(project.loadProject(dir, false));
        VcsProjectSettings settings = project.getVcsProjectSettings();
        settings.lfs = true;
        project.setVcsProjectSettings(settings);
        ASSERT_TRUE(project.saveProject());
        release(project);
    }
    EXPECT_EQ(readFile(dir / ".gitattributes"), mine);
}
