#ifndef PROCMAT_NODELIBRARY_H
#define PROCMAT_NODELIBRARY_H

#include "graph/Graph.h"

#include <filesystem>
#include <map>
#include <memory>
#include <string>
#include <utility>
#include <vector>

namespace jasperengine::editor::procmat {

    using Json = graph::Json;

    // A node the shipped library leaves out (S90 R20): its image differs between tiers for a reason
    // that is the node's own, so it is listed here and in the spec's Deviations, never patched around.
    struct LeftOutNode {
        const char* id;
        const char* reason;
    };

    // The ported node library as data (editor/procmat/nodes, generated by
    // tools/procmat/import_mm_nodes.py): descriptors by id, shared GLSL functions, port types and
    // the catalog's categories. Immutable once loaded, so it is shared between threads.
    class NodeLibrary {
    public:
        // Every "<name>.json" given, by file name; false and an error naming the file on bad data
        static std::shared_ptr<const NodeLibrary> fromFiles(const std::vector<std::pair<std::string, std::string>>& files, std::string& error);
        static std::shared_ptr<const NodeLibrary> fromDirectory(const std::filesystem::path& directory, std::string& error);
        // The library embedded in the editor, parsed once on first use
        static std::shared_ptr<const NodeLibrary> shipped();

        const Json* descriptor(const std::string& id) const;
        const std::map<std::string, Json>& descriptors() const { return nodes; }
        const Json* function(const std::string& id) const;
        const Json* portType(const std::string& name) const;
        const std::map<std::string, Json>& portTypes() const { return types; }
        // {display_name, tree_item, aliases?, parameters} of a node type the catalog lists; null for
        // the descriptors only other graphs reach
        const Json* catalogEntry(const std::string& id) const;
        // why R20 left this node out; null when it ships
        static const char* leftOutReason(const std::string& id);
        static const std::vector<LeftOutNode>& leftOutNodes();

    private:
        std::map<std::string, Json> nodes;
        std::map<std::string, Json> functions;
        std::map<std::string, Json> types;
        std::map<std::string, Json> entries;
    };

}

#endif
