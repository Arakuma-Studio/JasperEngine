std::string ScriptTemplates::lua(const std::string& classOrModuleName) {
    std::ostringstream out;
    out << "-- " << classOrModuleName << ".lua\n";
    out << "-- Auto-generated by JasperEngine Editor\n\n";

    // The module as a ScriptInstance subclass, a field per property: lua-language-server
    // then types self (self.scene, self.entity, the properties) and reports typos
    out << "---@class " << classOrModuleName << " : ScriptInstance\n";
    out << "---@field speed number\n";
    out << "---@field isActive boolean\n";

    // Script table used as the instance prototype
    out << "local " << classOrModuleName << " = {\n";
    out << "    -- Editor-exposed properties\n";
    out << "    properties = {\n";
    out << "        {\n";
    out << "            name = \"speed\",\n";
    out << "            displayName = \"Speed\",\n";
    out << "            type = \"float\",\n";
    out << "            default = 5.0\n";
    out << "        },\n";
    out << "        {\n";
    out << "            name = \"isActive\",\n";
    out << "            displayName = \"Is Active\",\n";
    out << "            type = \"bool\",\n";
    out << "            default = true\n";
    out << "        }\n";
    out << "    }\n";
    out << "}\n\n";

    // init(self) – called once by the engine (Project::initializeLuaScripts)
    out << "function " << classOrModuleName << ":init()\n";
    out << "    -- 'self.scene' and 'self.entity' are provided by the engine\n";
    out << "    RegisterEngineEvent(self, \"onUpdate\")\n";
    out << "    self.counter = 0\n";
    out << "end\n\n";

    // onUpdate(self) – optional; engine may call this every frame
    out << "function " << classOrModuleName << ":onUpdate()\n";
    out << "    if not self.isActive then return end\n\n";
    out << "    self.counter = self.counter + 1\n";
    out << "    if self.counter % 60 == 0 then\n";
    out << "        Log.print(\"[\" .. tostring(self.entity) .. \"] Counter: \" .. self.counter)\n";
    out << "    end\n";
    out << "end\n\n";

    out << "return " << classOrModuleName << "\n";
    return out.str();
}

ScriptTemplates::Files ScriptTemplates::cppScript(const std::string& classOrModuleName, const std::string& headerFileName) {
    Files files;
    {
        std::ostringstream out;
        out << "#pragma once\n\n";
        out << "#include \"ScriptBase.h\"\n";
        out << "#include \"Engine.h\"\n";
        out << "#include \"ScriptProperty.h\"\n\n";
        out << "class " << classOrModuleName << " : public jasperengine::ScriptBase {\n";
        out << "public:\n";
        out << "    // Example properties - you can add more!\n";
        out << "    DPROPERTY(\"Speed\")\n";
        out << "    float speed = 5.0f;\n\n";
        out << "    DPROPERTY(\"Is Active\")\n";
        out << "    bool isActive = true;\n\n";
        out << "    DPROPERTY(\"Counter\")\n";
        out << "    int counter = 0;\n\n";
        out << "    " << classOrModuleName << "(jasperengine::Scene* scene, jasperengine::Entity entity);\n";
        out << "    ~" << classOrModuleName << "();\n\n";
        out << "    void onUpdate();\n";
        out << "};\n";
        files.header = out.str();
    }
    {
        std::ostringstream out;
        out << "#include \"" << headerFileName << "\"\n\n";
        out << "using namespace jasperengine;\n\n";
        out << classOrModuleName << "::" << classOrModuleName << "(Scene* scene, Entity entity): ScriptBase(scene, entity) {\n";
        out << "    REGISTER_ENGINE_EVENT(onUpdate);\n\n";
        out << "}\n\n";
        out << classOrModuleName << "::~" << classOrModuleName << "() {\n";
        out << "\n";
        out << "}\n\n";
        out << "void " << classOrModuleName << "::onUpdate() {\n";
        out << "    if (!isActive) return;\n\n";
        out << "    // Example: Increment counter every frame\n";
        out << "    counter++;\n";
        out << "    if (counter % 60 == 0) {\n";
        out << "        Log::print(\"Counter: %d\\n\", counter);\n";
        out << "    }\n";
        out << "}\n\n";
        files.source = out.str();
    }
    return files;
}

ScriptTemplates::Files ScriptTemplates::cppSubclass(Scene* scene, Entity entity, const std::string& classOrModuleName,
                                                const std::string& headerFileName) {
    ProjectUtils::EntityClassInfo parentInfo = ProjectUtils::getEntityClassInfo(scene, entity);
    std::string parentClass = parentInfo.name;
    bool hasTransform = parentInfo.derivesObject;
    bool isMesh = parentInfo.derivesMesh;
    Files files;
    {
        std::ostringstream out;
        out << "#pragma once\n\n";
        out << "#include \"Primitive.h\"\n";
        out << "#include \"" << parentClass << ".h\"\n";
        out << "#include \"ScriptProperty.h\"\n\n";
        out << "class " << classOrModuleName << " : public jasperengine::" << parentClass << " {\n";
        out << "public:\n";
        out << "    // Example properties\n";
        out << "    DPROPERTY(\"Is Active\")\n";
        out << "    bool isActive = true;\n\n";
        if (hasTransform){
            out << "    DPROPERTY(\"Speed\")\n";
            out << "    float speed = 5.0f;\n\n";
            out << "    DPROPERTY(\"Target Position\")\n";
            out << "    jasperengine::Vector3 targetPosition = jasperengine::Vector3(0, 0, 0);\n\n";
            if (isMesh){
                out << "    DPROPERTY(\"Mesh Color\", Color4)\n";
                out << "    jasperengine::Vector4 meshColor = jasperengine::Vector4(1, 1, 1, 1);\n\n";
            }
        }
        out << "    " << classOrModuleName << "(jasperengine::Scene* scene, jasperengine::Entity entity);\n";
        out << "    virtual ~" << classOrModuleName << "();\n\n";
        out << "    void onUpdate();\n";
        out << "};\n";
        files.header = out.str();
    }
    {
        std::ostringstream out;
        out << "#include \"" << headerFileName << "\"\n\n";
        out << "using namespace jasperengine;\n\n";
        out << classOrModuleName << "::" << classOrModuleName << "(Scene* scene, Entity entity): " << parentClass << "(scene, entity) {\n";
        out << "    REGISTER_ENGINE_EVENT(onUpdate);\n\n";
        out << "}\n\n";
        out << classOrModuleName << "::~" << classOrModuleName << "() {\n";
        out << "\n";
        out << "}\n\n";
        out << "void " << classOrModuleName << "::onUpdate() {\n";
        out << "    if (!isActive) return;\n\n";
        if (hasTransform){
            out << "    // Example: move toward the target at 'speed' units per second.\n";
            out << "    // moveTowards() clamps the step to the remaining distance, so it\n";
            out << "    // never overshoots - even on the first frame where deltaTime is large.\n";
            out << "    float deltaTime = Engine::getDeltatime();\n";
            out << "    Vector3 currentPos = getPosition();\n";
            out << "    setPosition(currentPos.moveTowards(targetPosition, speed * deltaTime));\n";
            if (isMesh){
                out << "    setColor(meshColor);\n";
            }
        }
        out << "}\n\n";
        files.source = out.str();
    }
    return files;
}

std::string ScriptTemplates::cppSource(const std::string& name, bool includeHeader) {
    if (includeHeader) {
        return "#include \"" + name + ".h\"\n\nusing namespace jasperengine;\n";
    }
    return "// " + name + ".cpp\n\n#include \"Engine.h\"\n\nusing namespace jasperengine;\n";
}

std::string ScriptTemplates::cppHeader(const std::string& name) {
    return "#pragma once\n\n// " + name + ".h\n";
}
