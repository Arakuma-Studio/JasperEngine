namespace fs = std::filesystem;

namespace {

// the paths a warning names before "..."
constexpr size_t NAMED_PATHS = 5;

std::string named(const std::vector<std::string>& paths) {
    std::string out;
    for (size_t i = 0; i < paths.size() && i < NAMED_PATHS; i++) out += (i == 0 ? "" : ", ") + paths[i];
    if (paths.size() > NAMED_PATHS) out += ", ...";
    return out;
}

} // namespace

AudioCredits::Report AudioCredits::collect(const fs::path& assetsDir, const std::vector<fs::path>& shippedRelativePaths) {
    Report report;
    std::vector<fs::path> files;
    for (const fs::path& path : shippedRelativePaths) {
        if (Util::isAudioFile(path.string())) files.push_back(path.lexically_normal());
    }
    std::sort(files.begin(), files.end());
    files.erase(std::unique(files.begin(), files.end()), files.end());
    for (const fs::path& relative : files) {
        AudioProvenance provenance;
        std::string error;
        if (!AudioProvenance::load(assetsDir / relative, provenance, error) || provenance.isEmpty()) continue;
        const std::string path = FileUtils::pathToGenericUtf8(relative);
        const std::string licence = provenance.licence();
        if (licence.empty() || licence == AudioProvenance::LICENCE_UNKNOWN) {
            report.unknown.push_back(path);
        } else if (licence == AudioProvenance::LICENCE_GENERATED) {
            report.placeholders.push_back(path);
        } else {
            report.listed.push_back({path, licence, provenance.text("licence_url"), provenance.text("author"), provenance.text("source"),
                                     provenance.text("url"), provenance.text("attribution")});
        }
    }
    std::stable_sort(report.listed.begin(), report.listed.end(), [](const Entry& a, const Entry& b) {
        return a.licence != b.licence ? a.licence < b.licence : a.path < b.path;
    });
    return report;
}

std::string AudioCredits::render(const Report& report, const std::string& projectName) {
    std::string out = "Third-party audio in " + projectName + "\n\n"
                      "The licence of every audio file this build ships, from each file's provenance.\n"
                      "Generated by JasperEngine; regenerate it by exporting again.\n";
    auto line = [&out](const Entry& entry) {
        out += "  " + entry.path;
        if (!entry.author.empty()) out += " | " + entry.author;
        if (!entry.url.empty()) out += " | " + entry.url;
        out += " | " + entry.licence;
        if (!entry.licenceUrl.empty()) out += " " + entry.licenceUrl;
        if (!entry.attribution.empty() && entry.attribution != entry.author) out += " | Attribution: " + entry.attribution;
        out += "\n";
    };
    for (size_t i = 0; i < report.listed.size();) {
        const std::string& licence = report.listed[i].licence;
        out += "\n" + licence + (licence == "CC0-1.0" ? " (public domain; credit is not required)" : std::string()) + "\n";
        // Kenney's clips by pack, the pack's page naming it; others by path
        std::map<std::string, std::vector<const Entry*>> packs;
        for (; i < report.listed.size() && report.listed[i].licence == licence; i++) {
            const Entry& entry = report.listed[i];
            if (entry.source == "kenney") packs[entry.url].push_back(&entry);
            else line(entry);
        }
        for (const auto& [url, entries] : packs) {
            out += "  Kenney pack: " + url + " | " + entries.front()->author + "\n";
            for (const Entry* entry : entries) out += "    " + entry->path + "\n";
        }
    }
    if (!report.placeholders.empty()) {
        out += "\nPlaceholder sounds (generate_sound)\n";
        for (const std::string& path : report.placeholders) out += "  " + path + "\n";
    }
    if (!report.unknown.empty()) {
        out += "\nUnknown licence (set it in the clip's Inspector before you ship)\n";
        for (const std::string& path : report.unknown) out += "  " + path + "\n";
    }
    return out;
}

std::string AudioCredits::licenceWarning(const Report& report) {
    if (report.unknown.empty()) return std::string();
    return "audio with an unknown licence: " + named(report.unknown) + " (" + std::to_string(report.unknown.size()) +
           " file(s)): set provenance.licence with set_audio_import_settings or in the clip's Inspector";
}

std::string AudioCredits::placeholderWarning(const Report& report) {
    if (report.placeholders.empty()) return std::string();
    return "placeholder sounds in this build: " + named(report.placeholders) + " (" + std::to_string(report.placeholders.size()) +
           " file(s), generate_sound): replace them before release";
}
